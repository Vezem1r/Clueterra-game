SELECT h.id,
       h.country_id,
       c.iso_alpha2 AS country_code,
       c.name_en    AS country_name,
       h.category,
       h.hint_type,
       h.hint_text,
       h.image_url,
       h.original_image_url,
       h.image_source_page_url,
       h.image_author_name,
       h.image_attribution_text,
       h.image_license_label,
       h.image_license_url,
       h.difficulty,
       h.quality_score,
       h.source,
       h.source_indicator,
       h.source_year,
       h.ambiguity_count,
       h.times_used,
       h.times_correct,
       h.is_active,
       h.created_at,
       h.updated_at,
       h.review_retry_after_at,
       h.editorial_text_locked
FROM cl_media_schema.hint_projection h
         JOIN countries c ON c.id = h.country_id
