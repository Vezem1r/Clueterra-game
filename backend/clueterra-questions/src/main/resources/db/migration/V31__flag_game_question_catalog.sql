CREATE TABLE cl_schema.flag_game_question (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id   BIGINT      NOT NULL UNIQUE REFERENCES cl_schema.countries (id),
    iso2         CHAR(2)     NOT NULL UNIQUE,
    tier         SMALLINT    NOT NULL,
    region       VARCHAR(40) NOT NULL,
    subregion    VARCHAR(60) NOT NULL,
    names        JSONB       NOT NULL,
    content_hash CHAR(64)    NOT NULL,
    is_active    BOOLEAN     NOT NULL DEFAULT FALSE,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_flag_game_question_tier CHECK (tier BETWEEN 1 AND 5),
    CONSTRAINT chk_flag_game_question_iso CHECK (iso2 ~ '^[A-Z]{2}$'),
    CONSTRAINT chk_flag_game_question_hash CHECK (content_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX idx_flag_game_question_active
    ON cl_schema.flag_game_question (tier)
    WHERE is_active;

COMMENT ON TABLE cl_schema.flag_game_question IS
    'Guess-the-flag questions generated from the bundled country catalog; the pool matches the silhouette game.';

CREATE TABLE cl_schema.flag_game_hint (
    question_id BIGINT      NOT NULL REFERENCES cl_schema.flag_game_question (id) ON DELETE CASCADE,
    position    SMALLINT    NOT NULL,
    kind        VARCHAR(20) NOT NULL,
    cost_units  SMALLINT    NOT NULL,
    payload     JSONB       NOT NULL,
    PRIMARY KEY (question_id, position),
    CONSTRAINT chk_flag_game_hint_kind CHECK (
        (position = 1 AND kind = 'REGION' AND cost_units = 1)
        OR (position = 2 AND kind = 'INITIAL' AND cost_units = 1)
        OR (position = 3 AND kind = 'CAPITAL' AND cost_units = 2)
    )
);

COMMENT ON TABLE cl_schema.flag_game_hint IS
    'Ordered clues per flag question: region and the first letter of the name cost one unit, the verified capital two.';

CREATE OR REPLACE FUNCTION cl_schema.replace_flag_game_catalog(p_questions JSONB)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_question JSONB;
    v_question_id BIGINT;
    v_country_id BIGINT;
    v_previous_hash TEXT;
    v_changed INTEGER := 0;
BEGIN
    IF p_questions IS NULL OR jsonb_typeof(p_questions) <> 'array' OR jsonb_array_length(p_questions) = 0 THEN
        RAISE EXCEPTION 'Flag catalog is empty' USING ERRCODE = '22023';
    END IF;

    FOR v_question IN SELECT value FROM jsonb_array_elements(p_questions) LOOP
        SELECT id INTO v_country_id FROM cl_schema.countries WHERE iso_alpha2 = v_question ->> 'iso2';
        IF v_country_id IS NULL THEN
            RAISE EXCEPTION 'Unknown flag country %', v_question ->> 'iso2' USING ERRCODE = '22023';
        END IF;

        SELECT content_hash INTO v_previous_hash
        FROM cl_schema.flag_game_question WHERE iso2 = v_question ->> 'iso2';

        INSERT INTO cl_schema.flag_game_question (
            country_id, iso2, tier, region, subregion, names, content_hash, is_active, generated_at, updated_at
        ) VALUES (
            v_country_id, v_question ->> 'iso2', (v_question ->> 'tier')::SMALLINT,
            v_question ->> 'region', v_question ->> 'subregion', v_question -> 'names',
            v_question ->> 'contentHash', TRUE, NOW(), NOW()
        )
        ON CONFLICT (iso2) DO UPDATE SET
            tier = EXCLUDED.tier,
            region = EXCLUDED.region,
            subregion = EXCLUDED.subregion,
            names = EXCLUDED.names,
            content_hash = EXCLUDED.content_hash,
            is_active = TRUE,
            generated_at = CASE WHEN flag_game_question.content_hash = EXCLUDED.content_hash
                THEN flag_game_question.generated_at ELSE NOW() END,
            updated_at = NOW()
        RETURNING id INTO v_question_id;

        DELETE FROM cl_schema.flag_game_hint WHERE question_id = v_question_id;
        INSERT INTO cl_schema.flag_game_hint (question_id, position, kind, cost_units, payload)
        SELECT v_question_id, (hint ->> 'position')::SMALLINT, hint ->> 'kind',
               (hint ->> 'costUnits')::SMALLINT, hint -> 'payload'
        FROM jsonb_array_elements(v_question -> 'hints') hint;

        IF v_previous_hash IS DISTINCT FROM v_question ->> 'contentHash' THEN
            v_changed := v_changed + 1;
        END IF;
    END LOOP;

    UPDATE cl_schema.flag_game_question
    SET is_active = FALSE, updated_at = NOW()
    WHERE is_active
      AND iso2 NOT IN (SELECT value ->> 'iso2' FROM jsonb_array_elements(p_questions));

    RETURN v_changed;
END;
$$;
