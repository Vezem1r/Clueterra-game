CREATE TABLE cl_schema.silhouette_game_question (
    id                 BIGINT           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id         BIGINT           NOT NULL UNIQUE REFERENCES cl_schema.countries (id),
    iso2               CHAR(2)          NOT NULL UNIQUE,
    tier               SMALLINT         NOT NULL,
    region             VARCHAR(40)      NOT NULL,
    subregion          VARCHAR(60)      NOT NULL,
    center_lng         DOUBLE PRECISION NOT NULL,
    center_lat         DOUBLE PRECISION NOT NULL,
    bounds             JSONB            NOT NULL,
    names              JSONB            NOT NULL,
    shape_path         TEXT             NOT NULL,
    flag_colors        JSONB            NOT NULL,
    facts              JSONB            NOT NULL,
    content_hash       CHAR(64)         NOT NULL,
    is_active          BOOLEAN          NOT NULL DEFAULT FALSE,
    photo_resource_id  BIGINT           REFERENCES cl_media_schema.image_resource (id),
    landmark_qid       VARCHAR(20),
    landmark_names     JSONB,
    landmark_sitelinks INTEGER,
    photo_selection    VARCHAR(10)      NOT NULL DEFAULT 'AUTO',
    photo_selected_by  VARCHAR(255),
    photo_synced_at    TIMESTAMPTZ,
    generated_at       TIMESTAMPTZ      NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMPTZ      NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_silhouette_game_question_tier CHECK (tier BETWEEN 1 AND 5),
    CONSTRAINT chk_silhouette_game_question_iso CHECK (iso2 ~ '^[A-Z]{2}$'),
    CONSTRAINT chk_silhouette_game_question_center CHECK (
        center_lng BETWEEN -180 AND 180 AND center_lat BETWEEN -90 AND 90
    ),
    CONSTRAINT chk_silhouette_game_question_shape CHECK (shape_path ~ '^M'),
    CONSTRAINT chk_silhouette_game_question_hash CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_silhouette_game_question_landmark_qid CHECK (landmark_qid IS NULL OR landmark_qid ~ '^Q[0-9]+$'),
    CONSTRAINT chk_silhouette_game_question_landmark_sitelinks CHECK (landmark_sitelinks IS NULL OR landmark_sitelinks >= 0),
    CONSTRAINT chk_silhouette_game_question_photo_selection CHECK (
        (photo_selection = 'AUTO' AND photo_selected_by IS NULL)
        OR (photo_selection = 'MANUAL' AND photo_selected_by IS NOT NULL)
    )
);

CREATE INDEX idx_silhouette_game_question_active
    ON cl_schema.silhouette_game_question (tier)
    WHERE is_active;

CREATE INDEX idx_silhouette_game_question_photo
    ON cl_schema.silhouette_game_question (photo_resource_id)
    WHERE photo_resource_id IS NOT NULL;

COMMENT ON TABLE cl_schema.silhouette_game_question IS
    'Country silhouette questions generated from the bundled catalog and current country statistics; borders follow the EU position.';

COMMENT ON COLUMN cl_schema.silhouette_game_question.photo_resource_id IS
    'The best-known landmark photo of the country from Wikimedia Commons, ranked by the depicted landmark''s Wikipedia language editions.';

COMMENT ON COLUMN cl_schema.silhouette_game_question.photo_selection IS
    'AUTO photos follow the photo sync; MANUAL photos were chosen or cleared by an administrator and the sync leaves them alone.';

CREATE TABLE cl_schema.silhouette_game_hint (
    question_id BIGINT      NOT NULL REFERENCES cl_schema.silhouette_game_question (id) ON DELETE CASCADE,
    position    SMALLINT    NOT NULL,
    kind        VARCHAR(20) NOT NULL,
    cost_units  SMALLINT    NOT NULL,
    payload     JSONB       NOT NULL,
    PRIMARY KEY (question_id, position),
    CONSTRAINT chk_silhouette_game_hint_kind CHECK (
        (position = 1 AND kind = 'REGION' AND cost_units = 1)
        OR (position = 2 AND kind = 'LOCATION' AND cost_units = 1)
        OR (position = 3 AND kind IN ('CAPITAL', 'FLAG_COLORS') AND cost_units = 2)
        OR (position = 4 AND kind = 'LANDMARK' AND cost_units = 2)
    )
);

COMMENT ON TABLE cl_schema.silhouette_game_hint IS
    'Ordered clues per silhouette question; region and country clues cost one unit, capital and landmark photo two.';

CREATE OR REPLACE FUNCTION cl_schema.replace_silhouette_game_catalog(p_questions JSONB)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_question JSONB;
    v_question_id BIGINT;
    v_country_id BIGINT;
    v_previous_hash TEXT;
    v_changed INTEGER := 0;
BEGIN
    IF p_questions IS NULL OR jsonb_typeof(p_questions) <> 'array' OR jsonb_array_length(p_questions) = 0 THEN
        RAISE EXCEPTION 'Silhouette catalog is empty' USING ERRCODE = '22023';
    END IF;

    FOR v_question IN SELECT value FROM jsonb_array_elements(p_questions) LOOP
        SELECT id INTO v_country_id FROM cl_schema.countries WHERE iso_alpha2 = v_question ->> 'iso2';
        IF v_country_id IS NULL THEN
            RAISE EXCEPTION 'Unknown silhouette country %', v_question ->> 'iso2' USING ERRCODE = '22023';
        END IF;

        SELECT id, content_hash INTO v_question_id, v_previous_hash
        FROM cl_schema.silhouette_game_question WHERE iso2 = v_question ->> 'iso2';

        INSERT INTO cl_schema.silhouette_game_question (
            country_id, iso2, tier, region, subregion, center_lng, center_lat, bounds, names,
            shape_path, flag_colors, facts, content_hash, is_active, generated_at, updated_at
        ) VALUES (
            v_country_id, v_question ->> 'iso2', (v_question ->> 'tier')::SMALLINT,
            v_question ->> 'region', v_question ->> 'subregion',
            (v_question -> 'center' ->> 0)::DOUBLE PRECISION, (v_question -> 'center' ->> 1)::DOUBLE PRECISION,
            v_question -> 'bounds', v_question -> 'names', v_question ->> 'shapePath',
            v_question -> 'flagColors', v_question -> 'facts', v_question ->> 'contentHash', TRUE, NOW(), NOW()
        )
        ON CONFLICT (iso2) DO UPDATE SET
            tier = EXCLUDED.tier,
            region = EXCLUDED.region,
            subregion = EXCLUDED.subregion,
            center_lng = EXCLUDED.center_lng,
            center_lat = EXCLUDED.center_lat,
            bounds = EXCLUDED.bounds,
            names = EXCLUDED.names,
            shape_path = EXCLUDED.shape_path,
            flag_colors = EXCLUDED.flag_colors,
            facts = EXCLUDED.facts,
            content_hash = EXCLUDED.content_hash,
            is_active = TRUE,
            generated_at = CASE WHEN silhouette_game_question.content_hash = EXCLUDED.content_hash
                THEN silhouette_game_question.generated_at ELSE NOW() END,
            updated_at = NOW()
        RETURNING id INTO v_question_id;

        DELETE FROM cl_schema.silhouette_game_hint WHERE question_id = v_question_id;
        INSERT INTO cl_schema.silhouette_game_hint (question_id, position, kind, cost_units, payload)
        SELECT v_question_id, (hint ->> 'position')::SMALLINT, hint ->> 'kind',
               (hint ->> 'costUnits')::SMALLINT, hint -> 'payload'
        FROM jsonb_array_elements(v_question -> 'hints') hint;

        IF v_previous_hash IS DISTINCT FROM v_question ->> 'contentHash' THEN
            v_changed := v_changed + 1;
        END IF;
    END LOOP;

    UPDATE cl_schema.silhouette_game_question
    SET is_active = FALSE, updated_at = NOW()
    WHERE is_active
      AND iso2 NOT IN (SELECT value ->> 'iso2' FROM jsonb_array_elements(p_questions));

    RETURN v_changed;
END;
$$;

CREATE OR REPLACE FUNCTION cl_schema.save_silhouette_game_photo(
    p_iso2 TEXT,
    p_photo JSONB,
    p_selected_by TEXT DEFAULT NULL
) RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
DECLARE
    v_resource_id BIGINT;
    v_selection TEXT := CASE WHEN p_selected_by IS NULL THEN 'AUTO' ELSE 'MANUAL' END;
    v_current_selection TEXT;
BEGIN
    IF p_iso2 IS NULL OR p_iso2 !~ '^[A-Z]{2}$' THEN
        RAISE EXCEPTION 'Invalid country photo key: %', p_iso2 USING ERRCODE = '22023';
    END IF;

    SELECT photo_selection INTO v_current_selection
    FROM cl_schema.silhouette_game_question WHERE iso2 = p_iso2 FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'No silhouette question for %', p_iso2 USING ERRCODE = '22023';
    END IF;
    IF v_selection = 'AUTO' AND v_current_selection = 'MANUAL' THEN
        RETURN FALSE;
    END IF;

    IF p_photo IS NOT NULL THEN
        IF COALESCE(p_photo ->> 'objectKey', '') !~ '^country-photos/[0-9a-f]{64}\.jpg$'
           OR COALESCE(p_photo ->> 'sourcePageUrl', '') !~ '^https://commons\.wikimedia\.org/wiki/File:'
           OR NULLIF(BTRIM(p_photo ->> 'licenseLabel'), '') IS NULL THEN
            RAISE EXCEPTION 'Invalid country photo for %', p_iso2 USING ERRCODE = '22023';
        END IF;

        v_resource_id := cl_media_schema.register_image(
            'WIKIMEDIA_COMMONS', 'hint-images', p_photo ->> 'objectKey',
            p_photo ->> 'originalUrl', p_photo ->> 'sourcePageUrl',
            p_photo ->> 'authorName', p_photo ->> 'attributionText',
            p_photo ->> 'licenseLabel', p_photo ->> 'licenseUrl',
            p_photo ->> 'sourceSha1', NULL, p_photo ->> 'mimeType',
            (p_photo ->> 'width')::INTEGER, (p_photo ->> 'height')::INTEGER);

        UPDATE cl_media_schema.image_rendition
        SET byte_size = COALESCE((p_photo ->> 'byteSize')::BIGINT, byte_size),
            content_sha256 = COALESCE(p_photo ->> 'contentSha256', content_sha256),
            mime_type = 'image/jpeg',
            width = NULL,
            height = NULL,
            storage_status = 'AVAILABLE',
            orphaned_at = NULL,
            last_storage_check_at = NOW(),
            updated_at = NOW()
        WHERE storage_bucket = 'hint-images'
          AND object_key = p_photo ->> 'objectKey';
    END IF;

    UPDATE cl_schema.silhouette_game_question
    SET photo_resource_id = v_resource_id,
        landmark_qid = NULLIF(p_photo ->> 'landmarkQid', ''),
        landmark_names = p_photo -> 'landmarkNames',
        landmark_sitelinks = (p_photo ->> 'landmarkSitelinks')::INTEGER,
        photo_selection = v_selection,
        photo_selected_by = p_selected_by,
        photo_synced_at = NOW()
    WHERE iso2 = p_iso2;

    RETURN TRUE;
END;
$$;
