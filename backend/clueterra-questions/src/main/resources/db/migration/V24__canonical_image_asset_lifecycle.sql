CREATE OR REPLACE FUNCTION cl_media_schema.enforce_hint_suppressions()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_identity_action TEXT;
BEGIN
    SELECT suppression.action INTO v_identity_action
        FROM cl_schema.hint_suppression suppression
        WHERE suppression.is_active = TRUE
          AND suppression.country_id = NEW.country_id
          AND suppression.source = NEW.source
          AND suppression.category = NEW.category
          AND suppression.hint_type = NEW.hint_type
          AND suppression.source_indicator IS NOT DISTINCT FROM NEW.source_indicator
        LIMIT 1;

    IF v_identity_action = 'DELETE' AND TG_OP = 'INSERT' THEN
        RETURN NULL;
    ELSIF v_identity_action IS NOT NULL THEN
        NEW.is_active := FALSE;
    END IF;

    IF NEW.image_resource_id IS NOT NULL AND EXISTS (
        SELECT 1
        FROM cl_schema.hint_image_suppression suppression
        WHERE suppression.is_active = TRUE
          AND suppression.country_id = NEW.country_id
          AND suppression.source = NEW.source
          AND suppression.category = NEW.category
          AND suppression.hint_type = NEW.hint_type
          AND suppression.source_indicator IS NOT DISTINCT FROM NEW.source_indicator
          AND suppression.image_resource_id = NEW.image_resource_id
        UNION ALL
        SELECT 1
        FROM cl_media_schema.image_resource resource
        WHERE resource.id = NEW.image_resource_id
          AND resource.lifecycle_status <> 'ACTIVE'
    ) THEN
        NEW.image_resource_id := NULL;
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_zz_enforce_hint_suppressions
BEFORE INSERT OR UPDATE OF country_id, source, category, hint_type,
    source_indicator, image_resource_id, is_active
ON hints
FOR EACH ROW EXECUTE FUNCTION cl_media_schema.enforce_hint_suppressions();

CREATE OR REPLACE FUNCTION cl_media_schema.enforce_statistic_suppressions()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM cl_schema.statistic_suppression suppression
        WHERE suppression.is_active = TRUE
          AND suppression.country_id = NEW.country_id
          AND suppression.source = NEW.source
          AND suppression.source_indicator = NEW.indicator_code
          AND suppression.source_year IS NOT DISTINCT FROM NEW.year
          AND suppression.effective_date IS NOT DISTINCT FROM NEW.effective_date
    ) OR (NEW.image_resource_id IS NOT NULL AND EXISTS (
        SELECT 1
        FROM cl_media_schema.image_resource resource
        WHERE resource.id = NEW.image_resource_id
          AND resource.lifecycle_status <> 'ACTIVE'
    )) THEN
        NEW.is_current := FALSE;
    END IF;
    RETURN NEW;
END
$$;

