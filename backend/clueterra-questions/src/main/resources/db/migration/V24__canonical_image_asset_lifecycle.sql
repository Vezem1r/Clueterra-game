       rendition.mime_type,
       rendition.width,
       rendition.height,
       rendition.byte_size,
       rendition.storage_status
FROM cl_media_schema.image_resource resource
LEFT JOIN cl_media_schema.image_rights_revision rights
       ON rights.id = resource.current_rights_revision_id
LEFT JOIN LATERAL (
    SELECT stored.*
    FROM cl_media_schema.image_rendition stored
    WHERE stored.image_resource_id = resource.id
      AND stored.storage_status <> 'DELETED'
    ORDER BY CASE stored.storage_status WHEN 'AVAILABLE' THEN 0 ELSE 1 END,
             CASE stored.rendition_type
                 WHEN 'DISPLAY' THEN 0
                 WHEN 'ORIGINAL' THEN 1
                 WHEN 'MOBILE' THEN 2
                 WHEN 'THUMBNAIL' THEN 3
                 ELSE 4
             END,
             stored.id DESC
    LIMIT 1
) rendition ON TRUE;

