CREATE OR REPLACE FUNCTION cl_media_schema.image_provider(
    p_source TEXT,
    p_original_url TEXT,
    p_source_page_url TEXT
) RETURNS TEXT
LANGUAGE SQL
IMMUTABLE
AS $$
SELECT CASE
    WHEN UPPER(COALESCE(p_source, '')) = 'MAPILLARY' THEN 'MAPILLARY'
    WHEN COALESCE(p_source_page_url, '') ILIKE '%commons.wikimedia.org/%'
      OR COALESCE(p_original_url, '') ILIKE '%wikimedia.org/%' THEN 'WIKIMEDIA_COMMONS'
    WHEN UPPER(COALESCE(p_source, '')) IN ('HYDRO_RIVERS', 'NATURAL_EARTH') THEN 'BUNDLED'
    WHEN UPPER(COALESCE(p_source, '')) = 'MANUAL' THEN 'MANUAL'
    ELSE UPPER(COALESCE(NULLIF(p_source, ''), 'UNKNOWN'))
END
$$;

CREATE OR REPLACE FUNCTION cl_media_schema.image_object_key(
    p_image_url TEXT,
    p_bucket TEXT
) RETURNS TEXT
LANGUAGE SQL
IMMUTABLE
AS $$
SELECT CASE
    WHEN NULLIF(BTRIM(p_image_url), '') IS NULL THEN NULL
    WHEN p_image_url LIKE '%/' || p_bucket || '/%'
        THEN SPLIT_PART(p_image_url, '/' || p_bucket || '/', 2)
    WHEN p_image_url !~* '^https?://' AND p_image_url NOT LIKE '/api/%'
        THEN LTRIM(p_image_url, '/')
    ELSE NULL
END
$$;

CREATE OR REPLACE FUNCTION cl_media_schema.image_source_key(
    p_provider TEXT,
    p_source TEXT,
    p_external_id TEXT,
    p_bucket TEXT,
    p_object_key TEXT,
    p_original_url TEXT,
    p_source_page_url TEXT
) RETURNS TEXT
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
    v_value TEXT;
BEGIN
    IF p_provider = 'MAPILLARY' THEN
        v_value := COALESCE(
            NULLIF(BTRIM(p_external_id), ''),
            SUBSTRING(COALESCE(p_source_page_url, '') FROM '[?&]pKey=([0-9]+)'),
            SUBSTRING(COALESCE(p_original_url, '') FROM '[?&]pKey=([0-9]+)'));
    ELSIF p_provider = 'WIKIMEDIA_COMMONS' THEN
        v_value := COALESCE(
            NULLIF(SUBSTRING(
                REGEXP_REPLACE(BTRIM(COALESCE(p_source_page_url, '')), '[?#].*$', '')
                FROM '/wiki/File:(.+)$'), ''),
            NULLIF(SUBSTRING(
                REGEXP_REPLACE(BTRIM(COALESCE(p_original_url, '')), '[?#].*$', '')
                FROM '/([^/]+)$'), ''),
            NULLIF(BTRIM(p_external_id), ''));
        IF v_value IS NOT NULL THEN
            v_value := 'file:' || REPLACE(REPLACE(v_value, '_', ' '), '%20', ' ');
        END IF;
    ELSIF p_provider IN ('BUNDLED', 'MANUAL') THEN
        v_value := CONCAT_WS(
            ':',
            UPPER(COALESCE(p_source, p_provider)),
            p_bucket,
            COALESCE(
                NULLIF(BTRIM(p_object_key), ''),
                NULLIF(BTRIM(p_external_id), ''),
                NULLIF(BTRIM(p_source_page_url), ''),
                NULLIF(BTRIM(p_original_url), '')));
    ELSE
        v_value := COALESCE(
            NULLIF(BTRIM(p_external_id), ''),
            NULLIF(BTRIM(p_source_page_url), ''),
            NULLIF(BTRIM(p_original_url), ''),
            CONCAT_WS(':', UPPER(COALESCE(p_source, 'UNKNOWN')), p_bucket, p_object_key));
    END IF;
    RETURN LOWER(v_value);
END
$$;

CREATE OR REPLACE FUNCTION cl_media_schema.register_image(
    p_source TEXT,
    p_bucket TEXT,
    p_image_url TEXT,
    p_original_url TEXT,
    p_source_page_url TEXT,
    p_author_name TEXT,
    p_attribution_text TEXT,
    p_license_label TEXT,
    p_license_url TEXT,
    p_source_sha1 TEXT DEFAULT NULL,
    p_external_id TEXT DEFAULT NULL,
    p_mime_type TEXT DEFAULT NULL,
    p_width INTEGER DEFAULT NULL,
    p_height INTEGER DEFAULT NULL,
    p_rendition_type TEXT DEFAULT 'DISPLAY',
    p_source_key_override TEXT DEFAULT NULL
) RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_provider TEXT;
    v_object_key TEXT;
    v_source_key TEXT;
    v_resource_id BIGINT;
    v_rights_id BIGINT;
    v_fingerprint TEXT;
    v_current_rights RECORD;
BEGIN
    IF NULLIF(BTRIM(p_image_url), '') IS NULL
       AND NULLIF(BTRIM(p_original_url), '') IS NULL
       AND NULLIF(BTRIM(p_source_page_url), '') IS NULL THEN
        RETURN NULL;
    END IF;

    v_provider := cl_media_schema.image_provider(p_source, p_original_url, p_source_page_url);
    v_object_key := cl_media_schema.image_object_key(p_image_url, p_bucket);
    v_source_key := COALESCE(
        NULLIF(BTRIM(p_source_key_override), ''),
        cl_media_schema.image_source_key(
            v_provider,
            p_source,
            p_external_id,
            p_bucket,
            v_object_key,
            p_original_url,
            p_source_page_url));

    IF NULLIF(BTRIM(p_source_key_override), '') IS NULL
       AND v_provider IN ('BUNDLED', 'MANUAL')
       AND NULLIF(BTRIM(v_object_key), '') IS NULL
       AND NULLIF(BTRIM(p_external_id), '') IS NULL
       AND NULLIF(BTRIM(p_original_url), '') IS NULL
       AND NULLIF(BTRIM(p_source_page_url), '') IS NULL THEN
        v_source_key := LOWER(CONCAT_WS(
            ':',
            UPPER(COALESCE(p_source, v_provider)),
            p_bucket,
            NULLIF(BTRIM(p_image_url), '')));
    END IF;

    IF NULLIF(BTRIM(v_source_key), '') IS NULL THEN
        RAISE EXCEPTION 'Cannot derive canonical identity for image source %', p_source;
    END IF;

    IF v_object_key IS NOT NULL AND NULLIF(BTRIM(p_bucket), '') IS NOT NULL THEN
        PERFORM pg_advisory_xact_lock(
            hashtextextended(CONCAT(p_bucket, '/', v_object_key), 0));

        SELECT rendition.image_resource_id
        INTO v_resource_id
        FROM cl_media_schema.image_rendition rendition
        WHERE rendition.storage_bucket = p_bucket
          AND rendition.object_key = v_object_key;
    END IF;

    IF v_resource_id IS NULL THEN
        INSERT INTO cl_media_schema.image_resource (provider, source_key, external_id)
        VALUES (v_provider, v_source_key, NULLIF(BTRIM(p_external_id), ''))
        ON CONFLICT (provider, source_key) DO UPDATE
            SET external_id = COALESCE(cl_media_schema.image_resource.external_id, EXCLUDED.external_id),
                updated_at = NOW()
        RETURNING id INTO v_resource_id;
    ELSE
        UPDATE cl_media_schema.image_resource
        SET external_id = COALESCE(external_id, NULLIF(BTRIM(p_external_id), '')),
            updated_at = NOW()
        WHERE id = v_resource_id;
    END IF;

    PERFORM 1
    FROM cl_media_schema.image_resource
    WHERE id = v_resource_id
    FOR UPDATE;

    SELECT rights.*
    INTO v_current_rights
    FROM cl_media_schema.image_rights_revision rights
    WHERE rights.image_resource_id = v_resource_id
      AND rights.is_current = TRUE;

    IF FOUND THEN
        p_original_url := COALESCE(NULLIF(BTRIM(p_original_url), ''), v_current_rights.original_url);
        p_source_page_url := COALESCE(NULLIF(BTRIM(p_source_page_url), ''), v_current_rights.source_page_url);
        p_author_name := COALESCE(NULLIF(BTRIM(p_author_name), ''), v_current_rights.author_name);
        p_attribution_text := COALESCE(NULLIF(BTRIM(p_attribution_text), ''), v_current_rights.attribution_text);
        p_license_label := COALESCE(NULLIF(BTRIM(p_license_label), ''), v_current_rights.license_label);
        p_license_url := COALESCE(NULLIF(BTRIM(p_license_url), ''), v_current_rights.license_url);
        p_source_sha1 := COALESCE(NULLIF(BTRIM(p_source_sha1), ''), v_current_rights.source_sha1);
        p_mime_type := COALESCE(NULLIF(BTRIM(p_mime_type), ''), v_current_rights.mime_type);
        p_width := COALESCE(p_width, v_current_rights.width);
        p_height := COALESCE(p_height, v_current_rights.height);
    END IF;

    v_fingerprint := MD5(CONCAT_WS(E'\u001f',
        COALESCE(p_original_url, ''),
        COALESCE(p_source_page_url, ''),
        COALESCE(p_author_name, ''),
        COALESCE(p_attribution_text, ''),
        COALESCE(p_license_label, ''),
        COALESCE(p_license_url, ''),
        COALESCE(p_source_sha1, ''),
        COALESCE(p_mime_type, ''),
        COALESCE(p_width::TEXT, ''),
        COALESCE(p_height::TEXT, '')));

    SELECT id INTO v_rights_id
    FROM cl_media_schema.image_rights_revision
    WHERE image_resource_id = v_resource_id
      AND fingerprint = v_fingerprint
      AND is_current = TRUE;

    IF v_rights_id IS NULL THEN
        UPDATE cl_media_schema.image_rights_revision
        SET is_current = FALSE,
            valid_to = NOW()
        WHERE image_resource_id = v_resource_id
          AND is_current = TRUE;

        INSERT INTO cl_media_schema.image_rights_revision (
            image_resource_id,
            revision_number,
            fingerprint,
            original_url,
            download_url,
            source_page_url,
            author_name,
            attribution_text,
            license_label,
            license_url,
            source_sha1,
            mime_type,
            width,
            height
        )
        SELECT v_resource_id,
               COALESCE(MAX(revision_number), 0) + 1,
               v_fingerprint,
               NULLIF(BTRIM(p_original_url), ''),
               CASE
                   WHEN p_image_url ~* '^https?://' THEN NULLIF(BTRIM(p_image_url), '')
                   ELSE NULLIF(BTRIM(p_original_url), '')
               END,
               NULLIF(BTRIM(p_source_page_url), ''),
               NULLIF(BTRIM(p_author_name), ''),
               NULLIF(BTRIM(p_attribution_text), ''),
               NULLIF(BTRIM(p_license_label), ''),
               NULLIF(BTRIM(p_license_url), ''),
               NULLIF(BTRIM(p_source_sha1), ''),
               NULLIF(BTRIM(p_mime_type), ''),
               p_width,
               p_height
        FROM cl_media_schema.image_rights_revision
        WHERE image_resource_id = v_resource_id
        RETURNING id INTO v_rights_id;
    END IF;

    UPDATE cl_media_schema.image_resource
    SET current_rights_revision_id = v_rights_id,
        updated_at = NOW()
    WHERE id = v_resource_id;

    IF v_object_key IS NOT NULL AND NULLIF(BTRIM(p_bucket), '') IS NOT NULL THEN
        INSERT INTO cl_media_schema.image_rendition (
            image_resource_id,
            rights_revision_id,
            storage_bucket,
            object_key,
            rendition_type,
            format,
            mime_type,
            width,
            height
        )
        VALUES (
            v_resource_id,
            v_rights_id,
            p_bucket,
            v_object_key,
            UPPER(COALESCE(NULLIF(p_rendition_type, ''), 'DISPLAY')),
            NULLIF(LOWER(SUBSTRING(v_object_key FROM '\\.([^.]+)$')), ''),
            NULLIF(BTRIM(p_mime_type), ''),
            p_width,
            p_height
        )
        ON CONFLICT (storage_bucket, object_key) DO UPDATE
            SET rights_revision_id = EXCLUDED.rights_revision_id,
                rendition_type = EXCLUDED.rendition_type,
                mime_type = COALESCE(EXCLUDED.mime_type, cl_media_schema.image_rendition.mime_type),
                width = COALESCE(EXCLUDED.width, cl_media_schema.image_rendition.width),
                height = COALESCE(EXCLUDED.height, cl_media_schema.image_rendition.height),
                storage_status = 'AVAILABLE',
                orphaned_at = NULL,
                updated_at = NOW();
    END IF;

    RETURN v_resource_id;
END
$$;

CREATE OR REPLACE FUNCTION cl_media_schema.preserved_source_key(
    p_image_resource_id BIGINT,
    p_previous_object_key TEXT,
    p_new_object_key TEXT
) RETURNS TEXT
LANGUAGE SQL
STABLE
AS $$
SELECT CASE
    WHEN p_image_resource_id IS NOT NULL
     AND NULLIF(BTRIM(p_new_object_key), '') IS NOT NULL
     AND (NULLIF(BTRIM(p_previous_object_key), '') IS NULL
          OR p_previous_object_key IS NOT DISTINCT FROM p_new_object_key)
        THEN (
            SELECT resource.source_key
            FROM cl_media_schema.image_resource resource
            WHERE resource.id = p_image_resource_id
        )
    ELSE NULL
END
$$;

