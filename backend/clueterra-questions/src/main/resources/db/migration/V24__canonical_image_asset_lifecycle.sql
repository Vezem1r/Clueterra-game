CREATE OR REPLACE FUNCTION cl_media_schema.record_validation(
    p_image_resource_id BIGINT,
    p_validation_status TEXT,
    p_reason TEXT,
    p_next_validation_at TIMESTAMPTZ DEFAULT NULL
) RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_failures INTEGER;
BEGIN
    UPDATE cl_media_schema.image_resource
    SET validation_status = p_validation_status,
        lifecycle_status = CASE
            WHEN p_validation_status = 'AVAILABLE'
             AND NOT EXISTS (
                 SELECT 1
                 FROM cl_media_schema.image_resource_suppression suppression
                 WHERE suppression.image_resource_id = p_image_resource_id
                   AND suppression.is_active = TRUE
             ) THEN 'ACTIVE'
            ELSE lifecycle_status
        END,
        consecutive_failures = CASE
            WHEN p_validation_status IN ('AVAILABLE', 'UNSUPPORTED') THEN 0
            ELSE consecutive_failures + 1
        END,
        last_validated_at = NOW(),
        next_validation_at = COALESCE(
            p_next_validation_at,
            CASE
                WHEN p_validation_status IN ('AVAILABLE', 'UNSUPPORTED') THEN NOW() + INTERVAL '30 days'
                WHEN consecutive_failures >= 2 THEN NOW() + INTERVAL '7 days'
                ELSE NOW() + INTERVAL '1 day'
            END),
        last_validation_error = NULLIF(BTRIM(p_reason), ''),
        updated_at = NOW()
    WHERE id = p_image_resource_id
    RETURNING consecutive_failures INTO v_failures;
    RETURN COALESCE(v_failures, 0);
END
$$;

CREATE OR REPLACE FUNCTION cl_media_schema.quarantine_image_resource(
    p_image_resource_id BIGINT,
    p_reason TEXT,
    p_permanent BOOLEAN DEFAULT FALSE
) RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_owners INTEGER := 0;
    v_statistics INTEGER := 0;
    v_budget_questions INTEGER := 0;
BEGIN
    UPDATE cl_media_schema.image_resource
    SET lifecycle_status = CASE WHEN p_permanent THEN 'RETIRED' ELSE 'QUARANTINED' END,
        last_validation_error = p_reason,
        updated_at = NOW()
    WHERE id = p_image_resource_id;

    IF p_permanent THEN
        INSERT INTO cl_media_schema.image_resource_suppression (
            image_resource_id, action, reason, created_by)
        VALUES (p_image_resource_id, 'DELETE', p_reason, 'image-maintenance')
        ON CONFLICT (image_resource_id) DO UPDATE
            SET action = EXCLUDED.action,
                reason = EXCLUDED.reason,
                is_active = TRUE,
                resolved_at = NULL;

        UPDATE cl_media_schema.image_rendition
        SET storage_status = 'PENDING_DELETE',
            orphaned_at = COALESCE(orphaned_at, NOW()),
            updated_at = NOW()
        WHERE image_resource_id = p_image_resource_id
          AND storage_status <> 'DELETED';

        UPDATE cl_schema.daily_challenges challenge
        SET hints_json = (
            SELECT JSONB_AGG(
                CASE
                    WHEN NULLIF(element.payload ->> 'imageResourceId', '')::BIGINT
                            = p_image_resource_id
                        THEN element.payload
                            - 'imageUrl'
                            - 'originalImageUrl'
                            - 'imageSourcePageUrl'
                            - 'imageAuthorName'
                            - 'imageAttributionText'
                            - 'imageLicenseLabel'
                            - 'imageLicenseUrl'
                    ELSE element.payload
                END
                ORDER BY element.ordinality
            )::TEXT
            FROM JSONB_ARRAY_ELEMENTS(challenge.hints_json::JSONB)
                WITH ORDINALITY AS element(payload, ordinality)
        )
        WHERE challenge.is_active = TRUE
          AND EXISTS (
              SELECT 1
              FROM JSONB_ARRAY_ELEMENTS(challenge.hints_json::JSONB) payload
              WHERE NULLIF(payload ->> 'imageResourceId', '')::BIGINT
                    = p_image_resource_id
          );
    END IF;

    UPDATE cl_schema.hints
    SET is_active = FALSE,
        updated_at = NOW()
    WHERE image_resource_id = p_image_resource_id
      AND is_active = TRUE;
    GET DIAGNOSTICS v_owners = ROW_COUNT;

    UPDATE cl_schema.country_statistics
    SET is_current = FALSE
    WHERE image_resource_id = p_image_resource_id
      AND is_current = TRUE;
    GET DIAGNOSTICS v_statistics = ROW_COUNT;
    v_owners := v_owners + v_statistics;

    IF TO_REGCLASS('cl_budget_schema.project_image') IS NOT NULL THEN
        EXECUTE $statement$
            UPDATE cl_budget_schema.project project
            SET is_active = FALSE,
                updated_at = NOW()
            WHERE project.is_active = TRUE
              AND EXISTS (
                  SELECT 1
                  FROM cl_budget_schema.project_image image
                  WHERE image.project_id = project.id
                    AND image.image_resource_id = $1
              )
        $statement$ USING p_image_resource_id;
    END IF;

    IF TO_REGCLASS('cl_budget_schema.question') IS NOT NULL THEN
        EXECUTE $statement$
            UPDATE cl_budget_schema.question
            SET is_published = FALSE,
                retired_at = COALESCE(retired_at, NOW())
            WHERE image_resource_id = $1
              AND is_published = TRUE
        $statement$ USING p_image_resource_id;
        GET DIAGNOSTICS v_budget_questions = ROW_COUNT;
        v_owners := v_owners + v_budget_questions;
    END IF;

    IF TO_REGCLASS('cl_budget_staging.wikidata_candidate') IS NOT NULL THEN
        EXECUTE $statement$
            UPDATE cl_budget_staging.wikidata_candidate
            SET image_status = 'FAILED',
                image_failure_reason = LEFT($2, 1000),
                updated_at = NOW()
            WHERE image_resource_id = $1
              AND image_status <> 'FAILED'
        $statement$ USING p_image_resource_id, p_reason;
    END IF;

    IF TO_REGCLASS('cl_budget_schema.daily_challenge') IS NOT NULL
       AND TO_REGCLASS('cl_budget_schema.daily_challenge_question') IS NOT NULL
       AND TO_REGCLASS('cl_budget_schema.question_variant') IS NOT NULL THEN
        EXECUTE $statement$
            DELETE FROM cl_budget_schema.daily_challenge challenge
            WHERE challenge.challenge_date
                    > (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::DATE
              AND EXISTS (
                  SELECT 1
                  FROM cl_budget_schema.daily_challenge_question challenge_question
                  JOIN cl_budget_schema.question_variant variant
                    ON variant.id = challenge_question.question_variant_id
                  JOIN cl_budget_schema.question source_question
                    ON source_question.id = variant.source_question_id
                  LEFT JOIN cl_budget_schema.question comparison_question
                    ON comparison_question.id = variant.comparison_question_id
                  WHERE challenge_question.challenge_id = challenge.id
                    AND (
                        source_question.image_resource_id = $1
                        OR comparison_question.image_resource_id = $1
                    )
              )
        $statement$ USING p_image_resource_id;
    END IF;

    RETURN v_owners;
END
$$;

