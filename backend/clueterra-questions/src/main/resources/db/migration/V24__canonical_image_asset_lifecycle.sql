CREATE SCHEMA IF NOT EXISTS cl_media_schema;

CREATE TABLE IF NOT EXISTS cl_media_schema.image_resource (
    id                         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider                   VARCHAR(40) NOT NULL,
    source_key                 TEXT        NOT NULL,
    external_id                TEXT,
    lifecycle_status           VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    validation_status          VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    consecutive_failures       INTEGER     NOT NULL DEFAULT 0,
    next_validation_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_validated_at          TIMESTAMPTZ,
    last_validation_error      TEXT,
    current_rights_revision_id BIGINT,
    created_at                 TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at                 TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_image_resource_source UNIQUE (provider, source_key),
    CONSTRAINT chk_image_resource_lifecycle
        CHECK (lifecycle_status IN ('ACTIVE', 'QUARANTINED', 'RETIRED')),
    CONSTRAINT chk_image_resource_validation
        CHECK (validation_status IN ('PENDING', 'AVAILABLE', 'SOURCE_MISSING',
                                     'RESTRICTED_LICENSE', 'FETCH_FAILED', 'UNSUPPORTED')),
    CONSTRAINT chk_image_resource_failures CHECK (consecutive_failures >= 0)
);

CREATE INDEX IF NOT EXISTS idx_image_resource_audit_queue
    ON cl_media_schema.image_resource
        (lifecycle_status, next_validation_at, validation_status);

COMMENT ON TABLE cl_media_schema.image_resource IS
    'One logical external or bundled image, independent of where and how many times it is stored.';

CREATE TABLE IF NOT EXISTS cl_media_schema.image_rights_revision (
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_resource_id BIGINT      NOT NULL
        REFERENCES cl_media_schema.image_resource (id) ON DELETE CASCADE,
    revision_number  INTEGER     NOT NULL,
    fingerprint      VARCHAR(64) NOT NULL,
    original_url     TEXT,
    download_url     TEXT,
    source_page_url  TEXT,
    author_name      TEXT,
    attribution_text TEXT,
    license_label    VARCHAR(120),
    license_url      TEXT,
    source_sha1      VARCHAR(100),
    mime_type        VARCHAR(100),
    width            INTEGER,
    height           INTEGER,
    is_current       BOOLEAN     NOT NULL DEFAULT TRUE,
    observed_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    valid_from       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    valid_to         TIMESTAMPTZ,
    CONSTRAINT uq_image_rights_revision_number
        UNIQUE (image_resource_id, revision_number),
    CONSTRAINT chk_image_rights_revision_dimensions
        CHECK ((width IS NULL OR width > 0) AND (height IS NULL OR height > 0)),
    CONSTRAINT chk_image_rights_revision_period
        CHECK ((is_current AND valid_to IS NULL) OR (NOT is_current AND valid_to IS NOT NULL))
