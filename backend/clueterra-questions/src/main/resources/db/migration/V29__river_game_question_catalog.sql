CREATE TABLE cl_schema.river_game_question (
    id                        BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id                BIGINT        NOT NULL REFERENCES cl_schema.countries (id),
    river_key                 VARCHAR(80)   NOT NULL,
    name_en                   VARCHAR(160)  NOT NULL,
    answer_aliases            TEXT[]        NOT NULL DEFAULT ARRAY[]::TEXT[],
    rank_in_country           SMALLINT      NOT NULL,
    length_km                 NUMERIC(9, 1) NOT NULL,
    plain_image_key           VARCHAR(512)  NOT NULL,
    borders_image_key         VARCHAR(512)  NOT NULL,
    plain_image_resource_id   BIGINT        NOT NULL REFERENCES cl_media_schema.image_resource (id),
    borders_image_resource_id BIGINT        NOT NULL REFERENCES cl_media_schema.image_resource (id),
    course                    JSONB         NOT NULL,
    facts                     JSONB         NOT NULL,
    geometry_source_url       TEXT          NOT NULL,
    geometry_attribution      TEXT          NOT NULL,
    facts_source_url          TEXT          NOT NULL,
    content_hash              CHAR(64)      NOT NULL,
    is_active                 BOOLEAN       NOT NULL DEFAULT FALSE,
    generated_at              TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    updated_at                TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_river_game_question_identity UNIQUE (country_id, river_key),
    CONSTRAINT chk_river_game_rank CHECK (rank_in_country BETWEEN 1 AND 5),
    CONSTRAINT chk_river_game_length CHECK (length_km > 0),
    CONSTRAINT chk_river_game_name CHECK (BTRIM(name_en) <> ''),
    CONSTRAINT chk_river_game_key CHECK (river_key ~ '^[a-z0-9-]+$'),
    CONSTRAINT chk_river_game_image_keys CHECK (
        plain_image_key ~ '^river-game/[0-9a-f]{64}\.webp$'
        AND borders_image_key ~ '^river-game/[0-9a-f]{64}\.webp$'
        AND plain_image_key <> borders_image_key
    ),
    CONSTRAINT chk_river_game_distinct_images CHECK (plain_image_resource_id <> borders_image_resource_id),
    CONSTRAINT chk_river_game_course CHECK (
        jsonb_typeof(course -> 'bbox') = 'array' AND jsonb_array_length(course -> 'bbox') = 4
        AND jsonb_typeof(course -> 'coordinates') = 'array' AND jsonb_array_length(course -> 'coordinates') > 0
    ),
    CONSTRAINT chk_river_game_facts CHECK (jsonb_typeof(facts) = 'array' AND jsonb_array_length(facts) > 0),
    CONSTRAINT chk_river_game_content_hash CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_river_game_sources CHECK (
        geometry_source_url ~ '^https://' AND facts_source_url ~ '^https://'
        AND BTRIM(geometry_attribution) <> ''
    )
);

CREATE UNIQUE INDEX uq_river_game_active_country_rank
    ON cl_schema.river_game_question (country_id, rank_in_country)
    WHERE is_active = TRUE;

CREATE INDEX idx_river_game_active_difficulty
    ON cl_schema.river_game_question (rank_in_country, country_id)
    WHERE is_active = TRUE;

CREATE INDEX idx_river_game_question_river_key
    ON cl_schema.river_game_question (river_key);

CREATE INDEX idx_river_game_plain_image_resource
    ON cl_schema.river_game_question (plain_image_resource_id) WHERE is_active;

CREATE INDEX idx_river_game_borders_image_resource
    ON cl_schema.river_game_question (borders_image_resource_id) WHERE is_active;

COMMENT ON TABLE cl_schema.river_game_question IS
    'Source-backed river game catalog, owned by Questions and populated only by manual generation; map keys are immutable.';

COMMENT ON COLUMN cl_schema.river_game_question.rank_in_country IS
    'Length rank within a country: 1 easy, 2-3 medium, 4-5 hard.';

COMMENT ON COLUMN cl_schema.river_game_question.plain_image_key IS
    'Immutable MinIO key for the river-only WebP; public URL is resolved by API.';

COMMENT ON COLUMN cl_schema.river_game_question.borders_image_key IS
    'Immutable MinIO key for the same river WebP with real country borders.';

COMMENT ON COLUMN cl_schema.river_game_question.facts IS
    'Facts shown after the answer: length, countries, geography and the place clue, each as {kind, text, place?}.';

COMMENT ON COLUMN cl_schema.river_game_question.course IS
    'Simplified Natural Earth river course drawn on the globe: bbox [west, south, east, north] and MultiLineString coordinates.';

CREATE TABLE cl_schema.river_game_hint (
    question_id BIGINT      NOT NULL REFERENCES cl_schema.river_game_question (id) ON DELETE CASCADE,
    position    SMALLINT    NOT NULL,
    kind        VARCHAR(20) NOT NULL,
    hint_text   TEXT        NOT NULL,
    source_url  TEXT        NOT NULL,
    place       JSONB,
    PRIMARY KEY (question_id, position),
    CONSTRAINT uq_river_game_hint_kind UNIQUE (question_id, kind),
    CONSTRAINT chk_river_game_hint_position CHECK (position BETWEEN 1 AND 3),
    CONSTRAINT chk_river_game_hint_kind CHECK (
        (position = 1 AND kind = 'GEOGRAPHY')
        OR (position = 2 AND kind IN ('CITY', 'TRIBUTARY', 'COUNTRIES'))
        OR (position = 3 AND kind = 'NAME')
    ),
    CONSTRAINT chk_river_game_hint_place CHECK (
        (kind = 'CITY') = (place IS NOT NULL)
        AND (place IS NULL OR (
            BTRIM(place ->> 'name') <> ''
            AND jsonb_typeof(place -> 'lng') = 'number' AND jsonb_typeof(place -> 'lat') = 'number'
    ))
    ),
    CONSTRAINT chk_river_game_hint_text CHECK (BTRIM(hint_text) <> ''),
    CONSTRAINT chk_river_game_hint_source CHECK (source_url ~ '^https://')
);

COMMENT ON COLUMN cl_schema.river_game_hint.place IS
    'City pin for CITY clues: {name, lng, lat}; the globe marks it once the clue is open.';

CREATE OR REPLACE FUNCTION cl_schema.register_river_game_image(
    p_object_key TEXT,
    p_byte_size BIGINT,
    p_source_url TEXT,
    p_attribution TEXT
) RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_resource_id BIGINT;
    v_rights_id BIGINT;
    v_revision INTEGER;
    v_fingerprint TEXT;
    v_sha256 TEXT;
    v_rows INTEGER;
BEGIN
    IF p_object_key !~ '^river-game/[0-9a-f]{64}\.webp$'
       OR p_byte_size IS NULL OR p_byte_size <= 0
       OR p_source_url !~ '^https://' OR NULLIF(BTRIM(p_attribution), '') IS NULL THEN
        RAISE EXCEPTION 'Invalid river game image registration' USING ERRCODE = '22023';
    END IF;
    v_sha256 := SUBSTRING(p_object_key FROM '^river-game/([0-9a-f]{64})\.webp$');
    v_fingerprint := MD5(CONCAT_WS(CHR(31), p_source_url, p_attribution,
        'Public domain', 'https://www.naturalearthdata.com/about/terms-of-use/', 'image/webp'));

    INSERT INTO cl_media_schema.image_resource
        (provider, source_key, lifecycle_status, validation_status, next_validation_at)
    VALUES ('BUNDLED', 'river-game:' || p_object_key, 'ACTIVE', 'AVAILABLE', 'infinity'::TIMESTAMPTZ)
    ON CONFLICT (provider, source_key) DO UPDATE
        SET validation_status = 'AVAILABLE', next_validation_at = 'infinity'::TIMESTAMPTZ,
            updated_at = NOW()
    RETURNING id INTO v_resource_id;
    IF (SELECT lifecycle_status FROM cl_media_schema.image_resource WHERE id = v_resource_id) <> 'ACTIVE' THEN
        RAISE EXCEPTION 'River game image is quarantined or retired: %', p_object_key;
    END IF;

    SELECT id INTO v_rights_id
    FROM cl_media_schema.image_rights_revision
    WHERE image_resource_id = v_resource_id AND fingerprint = v_fingerprint AND is_current;
    IF v_rights_id IS NULL THEN
        UPDATE cl_media_schema.image_rights_revision
        SET is_current = FALSE, valid_to = NOW()
        WHERE image_resource_id = v_resource_id AND is_current;

        SELECT COALESCE(MAX(revision_number), 0) + 1 INTO v_revision
        FROM cl_media_schema.image_rights_revision WHERE image_resource_id = v_resource_id;
        INSERT INTO cl_media_schema.image_rights_revision
            (image_resource_id, revision_number, fingerprint, source_page_url,
             author_name, attribution_text, license_label, license_url, mime_type)
        VALUES (v_resource_id, v_revision, v_fingerprint, p_source_url,
                'Natural Earth', p_attribution, 'Public domain',
                'https://www.naturalearthdata.com/about/terms-of-use/', 'image/webp')
        RETURNING id INTO v_rights_id;
    END IF;

    UPDATE cl_media_schema.image_resource
    SET current_rights_revision_id = v_rights_id, updated_at = NOW()
    WHERE id = v_resource_id;

    INSERT INTO cl_media_schema.image_rendition
        (image_resource_id, rights_revision_id, storage_bucket, object_key,
         rendition_type, format, mime_type, width, height, byte_size, content_sha256,
         storage_status, orphaned_at)
    VALUES (v_resource_id, v_rights_id, 'hint-images', p_object_key,
            'DISPLAY', 'webp', 'image/webp', 1800, 1200, p_byte_size, v_sha256,
            'AVAILABLE', NULL)
    ON CONFLICT (storage_bucket, object_key) DO UPDATE
        SET rights_revision_id = EXCLUDED.rights_revision_id,
            format = EXCLUDED.format, mime_type = EXCLUDED.mime_type,
            width = EXCLUDED.width, height = EXCLUDED.height,
            byte_size = EXCLUDED.byte_size, content_sha256 = EXCLUDED.content_sha256,
            storage_status = 'AVAILABLE', orphaned_at = NULL, updated_at = NOW()
        WHERE cl_media_schema.image_rendition.image_resource_id = EXCLUDED.image_resource_id;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    IF v_rows <> 1 THEN
        RAISE EXCEPTION 'River image key belongs to another media resource: %', p_object_key;
    END IF;
    RETURN v_resource_id;
END;
$$;

CREATE OR REPLACE FUNCTION cl_schema.replace_river_game_country(
    p_country_code TEXT,
    p_questions JSONB
) RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_country_id BIGINT;
    v_question JSONB;
    v_entry JSONB;
    v_hint JSONB;
    v_question_id BIGINT;
    v_plain_resource_id BIGINT;
    v_borders_resource_id BIGINT;
    v_active_count INTEGER;
BEGIN
    IF p_country_code !~ '^[A-Z]{2}$' OR jsonb_typeof(p_questions) <> 'array'
       OR jsonb_array_length(p_questions) > 5 THEN
        RAISE EXCEPTION 'Invalid river catalog country payload' USING ERRCODE = '22023';
    END IF;
    SELECT id INTO v_country_id FROM cl_schema.countries
    WHERE iso_alpha2 = p_country_code FOR UPDATE;
    IF v_country_id IS NULL THEN
        RAISE EXCEPTION 'River catalog country is missing: %', p_country_code;
    END IF;

    SELECT COUNT(*) INTO v_active_count FROM cl_schema.river_game_question
    WHERE country_id = v_country_id AND is_active;
    IF v_active_count = jsonb_array_length(p_questions) AND NOT EXISTS (
        SELECT 1
        FROM jsonb_array_elements(p_questions) AS incoming(question)
        LEFT JOIN cl_schema.river_game_question current_question
          ON current_question.country_id = v_country_id
         AND current_question.river_key = (incoming.question -> 'entry' ->> 'riverKey')
         AND current_question.is_active
         AND current_question.content_hash = (incoming.question -> 'entry' ->> 'contentHash')
         AND current_question.plain_image_key = (incoming.question -> 'entry' ->> 'plainImageKey')
         AND current_question.borders_image_key = (incoming.question -> 'entry' ->> 'bordersImageKey')
        LEFT JOIN cl_media_schema.image_resource plain_resource
          ON plain_resource.id = current_question.plain_image_resource_id
         AND plain_resource.lifecycle_status = 'ACTIVE'
        LEFT JOIN cl_media_schema.image_resource borders_resource
          ON borders_resource.id = current_question.borders_image_resource_id
         AND borders_resource.lifecycle_status = 'ACTIVE'
        LEFT JOIN cl_media_schema.image_rendition plain_rendition
          ON plain_rendition.image_resource_id = plain_resource.id
         AND plain_rendition.storage_bucket = 'hint-images'
         AND plain_rendition.object_key = current_question.plain_image_key
         AND plain_rendition.storage_status = 'AVAILABLE'
        LEFT JOIN cl_media_schema.image_rendition borders_rendition
          ON borders_rendition.image_resource_id = borders_resource.id
         AND borders_rendition.storage_bucket = 'hint-images'
         AND borders_rendition.object_key = current_question.borders_image_key
         AND borders_rendition.storage_status = 'AVAILABLE'
        WHERE current_question.id IS NULL OR plain_rendition.id IS NULL OR borders_rendition.id IS NULL
    ) THEN
        RETURN 0;
    END IF;

    UPDATE cl_schema.river_game_question
    SET is_active = FALSE, updated_at = NOW()
    WHERE country_id = v_country_id AND is_active;

    FOR v_question IN SELECT value FROM jsonb_array_elements(p_questions) LOOP
        v_entry := v_question -> 'entry';
        v_plain_resource_id := cl_schema.register_river_game_image(
            v_entry ->> 'plainImageKey', (v_question ->> 'plainByteSize')::BIGINT,
            v_entry ->> 'geometrySourceUrl', v_entry ->> 'geometryAttribution');
        v_borders_resource_id := cl_schema.register_river_game_image(
            v_entry ->> 'bordersImageKey', (v_question ->> 'bordersByteSize')::BIGINT,
            v_entry ->> 'geometrySourceUrl', v_entry ->> 'geometryAttribution');

        INSERT INTO cl_schema.river_game_question (
            country_id, river_key, name_en, answer_aliases, rank_in_country,
            length_km, plain_image_key, borders_image_key,
            plain_image_resource_id, borders_image_resource_id, course, facts,
            geometry_source_url, geometry_attribution, facts_source_url, content_hash,
            is_active, generated_at, updated_at
        ) VALUES (
            v_country_id, v_entry ->> 'riverKey', v_entry ->> 'nameEn',
            ARRAY(SELECT jsonb_array_elements_text(COALESCE(v_entry -> 'aliases', '[]'::JSONB))),
            (v_entry ->> 'rankInCountry')::SMALLINT, (v_entry ->> 'lengthKm')::NUMERIC,
            v_entry ->> 'plainImageKey', v_entry ->> 'bordersImageKey',
            v_plain_resource_id, v_borders_resource_id, v_entry -> 'course', v_entry -> 'facts',
            v_entry ->> 'geometrySourceUrl', v_entry ->> 'geometryAttribution',
            v_entry ->> 'factsSourceUrl', v_entry ->> 'contentHash',
            TRUE, NOW(), NOW()
        )
        ON CONFLICT (country_id, river_key) DO UPDATE SET
            name_en = EXCLUDED.name_en,
            answer_aliases = EXCLUDED.answer_aliases,
            rank_in_country = EXCLUDED.rank_in_country,
            length_km = EXCLUDED.length_km,
            plain_image_key = EXCLUDED.plain_image_key,
            borders_image_key = EXCLUDED.borders_image_key,
            plain_image_resource_id = EXCLUDED.plain_image_resource_id,
            borders_image_resource_id = EXCLUDED.borders_image_resource_id,
            course = EXCLUDED.course,
            facts = EXCLUDED.facts,
            geometry_source_url = EXCLUDED.geometry_source_url,
            geometry_attribution = EXCLUDED.geometry_attribution,
            facts_source_url = EXCLUDED.facts_source_url,
            content_hash = EXCLUDED.content_hash,
            is_active = TRUE,
            generated_at = NOW(),
            updated_at = NOW()
        RETURNING id INTO v_question_id;

        DELETE FROM cl_schema.river_game_hint WHERE question_id = v_question_id;
        FOR v_hint IN SELECT value FROM jsonb_array_elements(v_entry -> 'hints') LOOP
            INSERT INTO cl_schema.river_game_hint
                (question_id, position, kind, hint_text, source_url, place)
            VALUES (v_question_id, (v_hint ->> 'position')::SMALLINT,
                    v_hint ->> 'kind', v_hint ->> 'text', v_hint ->> 'sourceUrl',
                    NULLIF(v_hint -> 'place', 'null'::JSONB));
        END LOOP;
    END LOOP;
    RETURN jsonb_array_length(p_questions);
END;
$$;

CREATE TABLE cl_schema.river_game_river_media (
    river_key         VARCHAR(80) PRIMARY KEY,
    wikipedia_url     TEXT,
    photo_resource_id BIGINT      REFERENCES cl_media_schema.image_resource (id),
    synced_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_river_game_media_key CHECK (river_key ~ '^q[0-9]+$'),
    CONSTRAINT chk_river_game_media_wikipedia CHECK (
        wikipedia_url IS NULL OR wikipedia_url ~ '^https://en\.wikipedia\.org/wiki/[^[:space:]]+$'
    )
);

CREATE INDEX idx_river_game_media_photo
    ON cl_schema.river_game_river_media (photo_resource_id)
    WHERE photo_resource_id IS NOT NULL;

COMMENT ON TABLE cl_schema.river_game_river_media IS
    'Answer media per river from Wikidata and Wikimedia Commons; shown only after a river is answered.';

CREATE OR REPLACE FUNCTION cl_schema.save_river_game_media(
    p_river_key TEXT,
    p_wikipedia_url TEXT,
    p_photo JSONB
) RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_resource_id BIGINT;
BEGIN
    IF p_river_key IS NULL OR p_river_key !~ '^q[0-9]+$' THEN
        RAISE EXCEPTION 'Invalid river media key: %', p_river_key USING ERRCODE = '22023';
    END IF;

    IF p_photo IS NOT NULL THEN
        IF COALESCE(p_photo ->> 'objectKey', '') !~ '^river-photos/[0-9a-f]{64}\.jpg$'
           OR COALESCE(p_photo ->> 'sourcePageUrl', '') !~ '^https://commons\.wikimedia\.org/wiki/File:'
           OR NULLIF(BTRIM(p_photo ->> 'licenseLabel'), '') IS NULL THEN
            RAISE EXCEPTION 'Invalid river photo for %', p_river_key USING ERRCODE = '22023';
        END IF;

        v_resource_id := cl_media_schema.register_image(
            'WIKIMEDIA_COMMONS', 'hint-images', p_photo ->> 'objectKey',
            p_photo ->> 'originalUrl', p_photo ->> 'sourcePageUrl',
            p_photo ->> 'authorName', p_photo ->> 'attributionText',
            p_photo ->> 'licenseLabel', p_photo ->> 'licenseUrl',
            p_photo ->> 'sourceSha1', NULL, p_photo ->> 'mimeType',
            (p_photo ->> 'width')::INTEGER, (p_photo ->> 'height')::INTEGER);

        UPDATE cl_media_schema.image_rendition
        SET byte_size = COALESCE((p_photo ->> 'byteSize')::BIGINT, byte_size),
            content_sha256 = COALESCE(p_photo ->> 'contentSha256', content_sha256),
            mime_type = 'image/jpeg',
            width = NULL,
            height = NULL,
            storage_status = 'AVAILABLE',
            orphaned_at = NULL,
            last_storage_check_at = NOW(),
            updated_at = NOW()
        WHERE storage_bucket = 'hint-images'
          AND object_key = p_photo ->> 'objectKey';
    END IF;

    INSERT INTO cl_schema.river_game_river_media (river_key, wikipedia_url, photo_resource_id, synced_at)
    VALUES (p_river_key, NULLIF(BTRIM(p_wikipedia_url), ''), v_resource_id, NOW())
    ON CONFLICT (river_key) DO UPDATE SET
        wikipedia_url = EXCLUDED.wikipedia_url,
        photo_resource_id = EXCLUDED.photo_resource_id,
        synced_at = NOW();

    RETURN v_resource_id;
END;
$$;
