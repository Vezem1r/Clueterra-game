CREATE TABLE IF NOT EXISTS countries (
    id                  BIGINT        PRIMARY KEY,
    iso_alpha2          VARCHAR(2)    NOT NULL UNIQUE,
    iso_alpha3          VARCHAR(3)    NOT NULL UNIQUE,
    name_en             VARCHAR(100)  NOT NULL,
    name_native         VARCHAR(100),
    region              VARCHAR(50),
    subregion           VARCHAR(50),
    capital             VARCHAR(100),
    flag_emoji          VARCHAR(10),
    flag_url            VARCHAR(255),
    difficulty_modifier DECIMAL(3, 2) NOT NULL DEFAULT 1.00,
    times_featured      INTEGER       DEFAULT 0,
    times_guessed       INTEGER       DEFAULT 0,
    success_rate        DECIMAL(5, 2),
    is_active           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_countries_is_active ON countries (is_active) WHERE is_active = TRUE;

CREATE INDEX IF NOT EXISTS idx_countries_region ON countries (region);

CREATE INDEX IF NOT EXISTS idx_countries_times_featured ON countries (times_featured ASC);

COMMENT ON TABLE countries IS 'Basic information about countries';

COMMENT ON COLUMN countries.id IS 'Primary key using TSID (time-sorted identifier)';

COMMENT ON COLUMN countries.iso_alpha2 IS 'ISO 3166-1 alpha-2 code (e.g., DE, US, JP)';

COMMENT ON COLUMN countries.iso_alpha3 IS 'ISO 3166-1 alpha-3 code (e.g., DEU, USA, JPN)';

COMMENT ON COLUMN countries.difficulty_modifier IS 'Modifier for hint difficulty calculation (1.0 = normal, >1.0 = harder, <1.0 = easier)';

COMMENT ON COLUMN countries.success_rate IS 'Player success rate for guessing this country (0-100%)';

COMMENT ON COLUMN countries.is_active IS 'Whether this country is currently used in the game';

COMMENT ON COLUMN countries.region IS 'Canonical gameplay region. The Americas are split into North America and South America for region-completion badges.';

COMMENT ON COLUMN countries.subregion IS 'Canonical gameplay subregion used for subregion-completion badges where available.';

