CREATE TABLE cl_schema.quiz_game_country (
    id           BIGINT           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id   BIGINT           NOT NULL UNIQUE REFERENCES cl_schema.countries (id),
    iso2         CHAR(2)          NOT NULL UNIQUE,
    tier         SMALLINT         NOT NULL,
    levels       SMALLINT         NOT NULL,
    region       VARCHAR(40)      NOT NULL,
    subregion    VARCHAR(60)      NOT NULL,
    names        JSONB            NOT NULL,
    longitude    DOUBLE PRECISION NOT NULL,
    latitude     DOUBLE PRECISION NOT NULL,
    neighbours   CHAR(2)[]        NOT NULL DEFAULT '{}',
    content_hash CHAR(64)         NOT NULL,
    is_active    BOOLEAN          NOT NULL DEFAULT FALSE,
    generated_at TIMESTAMPTZ      NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ      NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_quiz_game_country_tier CHECK (tier BETWEEN 1 AND 5),
    CONSTRAINT chk_quiz_game_country_levels CHECK (levels BETWEEN 1 AND 3),
    CONSTRAINT chk_quiz_game_country_iso CHECK (iso2 ~ '^[A-Z]{2}$'),
    CONSTRAINT chk_quiz_game_country_position CHECK (longitude BETWEEN -180 AND 180 AND latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_quiz_game_country_hash CHECK (content_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX idx_quiz_game_country_active
    ON cl_schema.quiz_game_country (tier)
    WHERE is_active;

COMMENT ON TABLE cl_schema.quiz_game_country IS
    'Stops of the world tour quiz: the silhouette pool with its verified land neighbours, centre for the route and the number of levels a player can reach there (each visit plays two questions of the next level).';

CREATE TABLE cl_schema.quiz_game_question (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_country_id BIGINT      NOT NULL REFERENCES cl_schema.quiz_game_country (id) ON DELETE CASCADE,
    kind            VARCHAR(20) NOT NULL,
    level           SMALLINT    NOT NULL,
    subject         JSONB,
    options         JSONB       NOT NULL,
    answer_index    SMALLINT    NOT NULL,
    fact            JSONB       NOT NULL,
    content_hash    CHAR(64)    NOT NULL,
    is_active       BOOLEAN     NOT NULL DEFAULT TRUE,
    generated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_quiz_game_question_kind UNIQUE (quiz_country_id, kind),
    CONSTRAINT chk_quiz_game_question_kind CHECK (kind IN (
        'FLAG', 'CAPITAL', 'NEIGHBOUR', 'CURRENCY', 'POPULATION', 'AREA', 'LEFT_DRIVING', 'DOMAIN',
        'LANDLOCKED', 'OUTLINE', 'COASTLINE', 'TOURISTS', 'PEAK', 'NEIGHBOUR_CAPITAL', 'HIGHEST_POINT',
        'NOT_NEIGHBOUR', 'LIFE_EXPECTANCY', 'WEALTH', 'HERITAGE', 'NEIGHBOUR_COUNT', 'FOREST', 'MEDIAN_AGE'
    )),
    CONSTRAINT chk_quiz_game_question_level CHECK (level BETWEEN 1 AND 3),
    CONSTRAINT chk_quiz_game_question_options CHECK (
        jsonb_typeof(options) = 'array' AND jsonb_array_length(options) BETWEEN 2 AND 4
        AND answer_index >= 0 AND answer_index < jsonb_array_length(options)
    ),
    CONSTRAINT chk_quiz_game_question_hash CHECK (content_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX idx_quiz_game_question_active
    ON cl_schema.quiz_game_question (quiz_country_id, level)
    WHERE is_active;

COMMENT ON TABLE cl_schema.quiz_game_question IS
    'Multiple-choice questions per stop, generated from the bundled catalog and checked statistics and split into levels 1-3 from easiest to hardest; subject names another country when the stop itself would give the answer away. A row keeps its id while its kind exists so answers stay linked.';

CREATE OR REPLACE FUNCTION cl_schema.replace_quiz_game_catalog(p_countries JSONB)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_country JSONB;
    v_question JSONB;
    v_country_row_id BIGINT;
    v_country_id BIGINT;
    v_previous_hash TEXT;
    v_changed INTEGER := 0;
BEGIN
    IF p_countries IS NULL OR jsonb_typeof(p_countries) <> 'array' OR jsonb_array_length(p_countries) = 0 THEN
        RAISE EXCEPTION 'Quiz catalog is empty' USING ERRCODE = '22023';
    END IF;

    FOR v_country IN SELECT value FROM jsonb_array_elements(p_countries) LOOP
        SELECT id INTO v_country_id FROM cl_schema.countries WHERE iso_alpha2 = v_country ->> 'iso2';
        IF v_country_id IS NULL THEN
            RAISE EXCEPTION 'Unknown quiz country %', v_country ->> 'iso2' USING ERRCODE = '22023';
        END IF;
        IF jsonb_array_length(COALESCE(v_country -> 'questions', '[]'::JSONB)) < 2 THEN
            RAISE EXCEPTION 'Quiz country % needs at least two questions', v_country ->> 'iso2' USING ERRCODE = '22023';
        END IF;

        INSERT INTO cl_schema.quiz_game_country (
            country_id, iso2, tier, levels, region, subregion, names, longitude, latitude, neighbours,
            content_hash, is_active, generated_at, updated_at
        ) VALUES (
            v_country_id, v_country ->> 'iso2', (v_country ->> 'tier')::SMALLINT, (v_country ->> 'levels')::SMALLINT,
            v_country ->> 'region', v_country ->> 'subregion', v_country -> 'names',
            (v_country ->> 'longitude')::DOUBLE PRECISION, (v_country ->> 'latitude')::DOUBLE PRECISION,
            ARRAY(SELECT jsonb_array_elements_text(v_country -> 'neighbours'))::CHAR(2)[],
            v_country ->> 'contentHash', TRUE, NOW(), NOW()
        )
        ON CONFLICT (iso2) DO UPDATE SET
            tier = EXCLUDED.tier,
            levels = EXCLUDED.levels,
            region = EXCLUDED.region,
            subregion = EXCLUDED.subregion,
            names = EXCLUDED.names,
            longitude = EXCLUDED.longitude,
            latitude = EXCLUDED.latitude,
            neighbours = EXCLUDED.neighbours,
            content_hash = EXCLUDED.content_hash,
            is_active = TRUE,
            generated_at = CASE WHEN quiz_game_country.content_hash = EXCLUDED.content_hash
                THEN quiz_game_country.generated_at ELSE NOW() END,
            updated_at = NOW()
        RETURNING id INTO v_country_row_id;

        FOR v_question IN SELECT value FROM jsonb_array_elements(v_country -> 'questions') LOOP
            SELECT content_hash INTO v_previous_hash
            FROM cl_schema.quiz_game_question
            WHERE quiz_country_id = v_country_row_id AND kind = v_question ->> 'kind';

            INSERT INTO cl_schema.quiz_game_question (
                quiz_country_id, kind, level, subject, options, answer_index, fact, content_hash,
                is_active, generated_at, updated_at
            ) VALUES (
                v_country_row_id, v_question ->> 'kind', (v_question ->> 'level')::SMALLINT,
                NULLIF(v_question -> 'subject', 'null'::JSONB), v_question -> 'options', (v_question ->> 'answerIndex')::SMALLINT, v_question -> 'fact',
                v_question ->> 'contentHash', TRUE, NOW(), NOW()
            )
            ON CONFLICT (quiz_country_id, kind) DO UPDATE SET
                level = EXCLUDED.level,
                subject = EXCLUDED.subject,
                options = EXCLUDED.options,
                answer_index = EXCLUDED.answer_index,
                fact = EXCLUDED.fact,
                content_hash = EXCLUDED.content_hash,
                is_active = TRUE,
                generated_at = CASE WHEN quiz_game_question.content_hash = EXCLUDED.content_hash
                    THEN quiz_game_question.generated_at ELSE NOW() END,
                updated_at = NOW();

            IF v_previous_hash IS DISTINCT FROM v_question ->> 'contentHash' THEN
                v_changed := v_changed + 1;
            END IF;
        END LOOP;

        UPDATE cl_schema.quiz_game_question
        SET is_active = FALSE, updated_at = NOW()
        WHERE quiz_country_id = v_country_row_id
          AND is_active
          AND kind NOT IN (SELECT value ->> 'kind' FROM jsonb_array_elements(v_country -> 'questions'));
    END LOOP;

    UPDATE cl_schema.quiz_game_country
    SET is_active = FALSE, updated_at = NOW()
    WHERE is_active
      AND iso2 NOT IN (SELECT value ->> 'iso2' FROM jsonb_array_elements(p_countries));

    RETURN v_changed;
END;
$$;
