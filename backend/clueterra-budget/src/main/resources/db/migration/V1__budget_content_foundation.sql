CREATE OR REPLACE FUNCTION cl_budget_schema.enforce_project_image_resource_lifecycle()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.image_resource_id IS NULL OR EXISTS (
        SELECT 1
        FROM cl_media_schema.image_resource resource
        WHERE resource.id = NEW.image_resource_id
          AND resource.lifecycle_status <> 'ACTIVE'
    ) THEN
        RAISE EXCEPTION 'Project image requires an active canonical image resource';
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_enforce_project_image_resource_lifecycle
BEFORE INSERT OR UPDATE OF image_resource_id
ON cl_budget_schema.project_image
FOR EACH ROW EXECUTE FUNCTION cl_budget_schema.enforce_project_image_resource_lifecycle();

CREATE OR REPLACE FUNCTION cl_budget_schema.enforce_question_image_resource_lifecycle()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.image_resource_id IS NOT NULL AND EXISTS (
        SELECT 1
        FROM cl_media_schema.image_resource resource
        WHERE resource.id = NEW.image_resource_id
          AND resource.lifecycle_status <> 'ACTIVE'
    ) THEN
        NEW.is_published := FALSE;
        NEW.retired_at := COALESCE(NEW.retired_at, NOW());
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_enforce_budget_question_image_lifecycle
