CREATE OR REPLACE FUNCTION cl_budget_schema.publish_budget_candidate_image(
    p_wikidata_id TEXT,
    p_category TEXT,
    p_page_id BIGINT,
    p_source_sha1 TEXT,
    p_file_title TEXT,
    p_object_key TEXT,
    p_original_url TEXT,
    p_source_page_url TEXT,
    p_author_name TEXT,
    p_credit TEXT,
    p_license_label TEXT,
    p_license_url TEXT,
    p_description TEXT,
    p_mime_type TEXT,
    p_source_bytes BIGINT,
    p_width INTEGER,
    p_height INTEGER,
    p_quality_score INTEGER,
    p_snapshot_at DATE
) RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_author_name TEXT;
    v_credit TEXT;
    v_image_resource_id BIGINT;
BEGIN
    SELECT CASE
               WHEN candidate.source_payload #>> '{imageAttributionOverride,fileTitle}' = p_file_title
                   THEN candidate.source_payload #>> '{imageAttributionOverride,authorName}'
               ELSE p_author_name
           END,
           CASE
               WHEN candidate.source_payload #>> '{imageAttributionOverride,fileTitle}' = p_file_title
                   THEN candidate.source_payload #>> '{imageAttributionOverride,credit}'
               ELSE p_credit
           END
    INTO v_author_name, v_credit
    FROM cl_budget_staging.wikidata_candidate candidate
    WHERE candidate.wikidata_id = p_wikidata_id
      AND candidate.category = p_category
      AND candidate.last_fetched
      AND candidate.editorial_status <> 'REJECTED'
      AND candidate.image_status = 'PROCESSING'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Candidate %/% has no claimed image', p_wikidata_id, p_category;
    END IF;

    v_image_resource_id := cl_media_schema.register_image(
        'WIKIMEDIA_COMMONS',
        'budget-images',
        p_object_key,
        p_original_url,
        p_source_page_url,
        v_author_name,
        COALESCE(NULLIF(BTRIM(v_credit), ''), v_author_name || ' / Wikimedia Commons'),
        p_license_label,
        p_license_url,
        p_source_sha1,
        p_page_id::TEXT,
        p_mime_type,
        p_width,
        p_height);

    UPDATE cl_media_schema.image_rendition
    SET byte_size = p_source_bytes,
        updated_at = NOW()
    WHERE image_resource_id = v_image_resource_id
      AND storage_bucket = 'budget-images'
      AND object_key = p_object_key;

    UPDATE cl_budget_staging.wikidata_candidate
    SET image_resource_id = v_image_resource_id,
        image_file_title = p_file_title,
        image_description = p_description,
        image_quality_score = p_quality_score,
        image_status = 'AVAILABLE',
        image_failure_reason = NULL,
        updated_at = NOW()
    WHERE wikidata_id = p_wikidata_id
      AND category = p_category;

    IF EXISTS (
        SELECT 1
        FROM cl_budget_staging.wikidata_candidate candidate
        WHERE candidate.wikidata_id = p_wikidata_id
          AND candidate.category = p_category
          AND (candidate.quality_status = 'AUTO_APPROVED'
               OR candidate.editorial_status = 'APPROVED')) THEN
        RETURN cl_budget_schema.publish_wikidata_candidate(
            p_wikidata_id,
            p_category,
            p_snapshot_at);
    END IF;
    RETURN NULL;
END
$$;

CREATE OR REPLACE FUNCTION cl_budget_schema.edit_budget_candidate (
    p_wikidata_id TEXT,
    p_category TEXT,
    p_edited_by TEXT,
    p_content JSONB
)
RETURNS TABLE (updated BOOLEAN, published_question_id BIGINT)
AS $$
DECLARE
    v_candidate RECORD;
    v_answer JSONB;
    v_image_changed BOOLEAN;
    v_payload JSONB;
BEGIN
    IF p_content IS NULL OR JSONB_TYPEOF(p_content) <> 'object' THEN
        RAISE EXCEPTION 'Budget candidate edit must be a JSON object';
    END IF;
    IF JSONB_TYPEOF(p_content -> 'costClaims') <> 'array'
        OR JSONB_ARRAY_LENGTH(p_content -> 'costClaims') = 0
        OR JSONB_TYPEOF(p_content -> 'metrics') <> 'array'
        OR JSONB_TYPEOF(p_content -> 'milestones') <> 'array' THEN
        RAISE EXCEPTION 'Budget candidate edit contains invalid fact collections';
    END IF;

    SELECT candidate.* INTO v_candidate
    FROM cl_budget_staging.wikidata_candidate candidate
    WHERE candidate.wikidata_id = p_wikidata_id
        AND candidate.category = p_category
        AND candidate.last_fetched
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Budget candidate %/% does not exist', p_wikidata_id, p_category;
    END IF;

    SELECT claim.value INTO v_answer
    FROM JSONB_ARRAY_ELEMENTS(p_content -> 'costClaims') claim(value)
    WHERE COALESCE((claim.value ->> 'answer')::BOOLEAN, FALSE);

    IF v_answer IS NULL
        OR NOT COALESCE((v_answer ->> 'primary')::BOOLEAN, FALSE)
        OR (
            SELECT COUNT(*)
            FROM JSONB_ARRAY_ELEMENTS(p_content -> 'costClaims') claim(value)
            WHERE COALESCE((claim.value ->> 'answer')::BOOLEAN, FALSE)
        ) <> 1 THEN
        RAISE EXCEPTION 'Exactly one primary cost claim must be the playable answer';
    END IF;

    v_image_changed := v_candidate.image_file_title IS DISTINCT FROM p_content ->> 'imageFileTitle';
    v_payload := (v_candidate.source_payload
            - 'costClaims' - 'metrics' - 'milestones' - 'costSnapshot' - 'descriptionSource')
        || JSONB_BUILD_OBJECT(
            'costSource', v_answer ->> 'sourceKey',
            'costEvidence', v_answer ->> 'evidenceText',
            'costSnapshot', v_answer - 'primary' - 'answer',
            'costClaims', p_content -> 'costClaims',
            'metrics', p_content -> 'metrics',
            'milestones', p_content -> 'milestones',
            'editorialEdit', JSONB_BUILD_OBJECT('editedBy', p_edited_by, 'editedAt', NOW())
        );
    IF p_content -> 'descriptionSource' IS NOT NULL
        AND JSONB_TYPEOF(p_content -> 'descriptionSource') = 'object' THEN
        v_payload := v_payload || JSONB_BUILD_OBJECT('descriptionSource', p_content -> 'descriptionSource');
    END IF;

    UPDATE cl_budget_staging.wikidata_candidate
    SET name = BTRIM(p_content ->> 'name'),
        description = BTRIM(p_content ->> 'description'),
        country_code = p_content ->> 'countryCode',
        country_name = BTRIM(p_content ->> 'countryName'),
        region_code = p_content ->> 'regionCode',
        project_year = NULLIF(p_content ->> 'projectYear', '')::INTEGER,
        difficulty = p_content ->> 'difficulty',
        image_file_title = BTRIM(p_content ->> 'imageFileTitle'),
        image_resource_id = CASE WHEN v_image_changed THEN NULL ELSE image_resource_id END,
        image_description = CASE WHEN v_image_changed THEN NULL ELSE image_description END,
        image_quality_score = CASE WHEN v_image_changed THEN NULL ELSE image_quality_score END,
        image_status = CASE WHEN v_image_changed THEN 'PENDING' ELSE image_status END,
        image_attempt_count = CASE WHEN v_image_changed THEN 0 ELSE image_attempt_count END,
        image_last_attempted_at = CASE WHEN v_image_changed THEN NULL ELSE image_last_attempted_at END,
        image_failure_reason = CASE WHEN v_image_changed THEN NULL ELSE image_failure_reason END,
        source_cost_amount = (
            (v_answer ->> 'sourceAmountLow')::NUMERIC
            + (v_answer ->> 'sourceAmountHigh')::NUMERIC
        ) / 2,
        source_cost_currency = v_answer ->> 'sourceCurrency',
        answer_cost_usd = (
            (v_answer ->> 'amountUsdLow')::NUMERIC
            + (v_answer ->> 'amountUsdHigh')::NUMERIC
        ) / 2,
        cost_year = NULLIF(v_answer ->> 'costYear', '')::INTEGER,
        cost_units_per_usd = (v_answer ->> 'unitsPerUsd')::NUMERIC,
        cost_exchange_rate_date = (v_answer ->> 'exchangeRateDate')::DATE,
        cost_source_name = BTRIM(v_answer ->> 'sourceName'),
        cost_source_url = v_answer ->> 'sourceUrl',
        cost_reference_url = NULLIF(BTRIM(v_answer ->> 'referenceUrl'), ''),
        cost_normalization_note = BTRIM(v_answer ->> 'normalizationNote'),
        source_payload = v_payload,
        quality_status = 'NEEDS_REVIEW',
        editorial_content = p_content,
        content_edited_by = p_edited_by,
        content_edited_at = NOW(),
        updated_at = NOW()
    WHERE wikidata_id = p_wikidata_id
        AND category = p_category;

    published_question_id := NULL;
    IF v_candidate.editorial_status = 'APPROVED'
        AND NOT v_image_changed
        AND v_candidate.image_status = 'AVAILABLE'
        AND v_candidate.image_resource_id IS NOT NULL THEN
        published_question_id := cl_budget_schema.publish_wikidata_candidate(
            p_wikidata_id, p_category, CURRENT_DATE);
    ELSE
        PERFORM cl_budget_schema.retire_budget_project(p_wikidata_id);
    END IF;
    updated := TRUE;
    RETURN NEXT;
END;
$$
LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION cl_budget_schema.republish_available_budget_candidates (
    p_category TEXT,
    p_snapshot_at DATE
)
    RETURNS INTEGER
    AS $$
DECLARE
    v_candidate RECORD;
    v_published INTEGER := 0;
BEGIN
    FOR v_candidate IN
        SELECT
            candidate.wikidata_id,
            candidate.category
        FROM cl_budget_staging.wikidata_candidate candidate
        WHERE (p_category IS NULL OR candidate.category = p_category)
            AND candidate.last_fetched
            AND candidate.quality_status = 'AUTO_APPROVED'
            AND candidate.editorial_status = 'NONE'
            AND candidate.image_status = 'AVAILABLE'
            AND candidate.image_resource_id IS NOT NULL
    LOOP
        PERFORM cl_budget_schema.publish_wikidata_candidate(
            v_candidate.wikidata_id,
            v_candidate.category,
            p_snapshot_at
        );
        v_published := v_published + 1;
    END LOOP;

    RETURN v_published;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION cl_budget_schema.fail_budget_candidate_image (p_wikidata_id TEXT, p_category TEXT, p_failure_reason TEXT)
    RETURNS BOOLEAN
    AS $$
BEGIN
    UPDATE
        cl_budget_staging.wikidata_candidate candidate
    SET
        image_status = 'FAILED',
        image_failure_reason =
    LEFT (p_failure_reason,
        1000),
    updated_at = NOW()
WHERE
    candidate.wikidata_id = p_wikidata_id
        AND candidate.category = p_category
        AND candidate.image_status = 'PROCESSING';
    RETURN FOUND;
END;
$$
LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION cl_budget_schema.reset_budget_candidate_image_failures ()
    RETURNS INTEGER
    AS $$
DECLARE
    v_updated INTEGER;
BEGIN
    UPDATE
        cl_budget_staging.wikidata_candidate candidate
    SET
        image_status = 'PENDING',
        image_failure_reason = NULL,
        updated_at = NOW()
    WHERE
        candidate.last_fetched
        AND candidate.editorial_status <> 'REJECTED'
        AND candidate.image_status = 'FAILED';
    GET DIAGNOSTICS v_updated = ROW_COUNT;
    RETURN v_updated;
END;
$$
LANGUAGE plpgsql;
