CREATE OR REPLACE FUNCTION cl_budget_schema.enforce_budget_project_activation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.is_active AND EXISTS (
        SELECT 1
        FROM cl_budget_schema.project_image image
        JOIN cl_media_schema.image_resource resource
          ON resource.id = image.image_resource_id
        WHERE image.project_id = NEW.id
          AND resource.lifecycle_status <> 'ACTIVE'
    ) THEN
        RAISE EXCEPTION 'Project % uses a quarantined or retired image resource', NEW.id;
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_enforce_budget_project_activation
BEFORE INSERT OR UPDATE OF is_active
ON cl_budget_schema.project
FOR EACH ROW EXECUTE FUNCTION cl_budget_schema.enforce_budget_project_activation();

-- Atomic sync, moderation, enrichment and publication operations.
CREATE OR REPLACE FUNCTION cl_budget_schema.start_sync_run (p_source_code TEXT, p_stale_before TIMESTAMP WITH TIME ZONE)
    RETURNS BIGINT
    AS $$
DECLARE
    v_run_id BIGINT;
BEGIN
    UPDATE
        cl_budget_schema.sync_run
    SET
        status = 'FAILED',
        completed_at = NOW(),
        error_message = 'Automatically closed after exceeding the stale-run timeout'
    WHERE
        source_code = p_source_code
        AND status = 'RUNNING'
        AND heartbeat_at < p_stale_before;
    INSERT INTO cl_budget_schema.sync_run (
        source_code,
        status)
    VALUES (
        p_source_code,
        'RUNNING')
ON CONFLICT (
    source_code)
WHERE
    status = 'RUNNING'
        DO NOTHING
    RETURNING
        id INTO v_run_id;
    RETURN v_run_id;
END;
$$
