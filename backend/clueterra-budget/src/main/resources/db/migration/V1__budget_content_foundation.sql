-- Durable observability for deciding whether every source contributes useful content.
CREATE OR REPLACE VIEW cl_budget_schema.source_project_contribution AS
WITH source_facts AS (
    SELECT
        snapshot.source_code,
        cost.project_id,
        1 AS cost_claims,
        0 AS metric_claims,
        0 AS milestones,
        0 AS image_claims,
        cost.created_at AS evidence_at
    FROM
        cl_budget_schema.project_cost
        COST
        JOIN cl_budget_schema.source_snapshot SNAPSHOT ON snapshot.id = cost.source_snapshot_id
UNION ALL
SELECT
    snapshot.source_code,
    metric.project_id,
    0,
    1,
    0,
    0,
    metric.created_at
FROM
    cl_budget_schema.project_metric metric
    JOIN cl_budget_schema.source_snapshot SNAPSHOT ON snapshot.id = metric.source_snapshot_id
UNION ALL
SELECT
    snapshot.source_code,
    milestone.project_id,
    0,
    0,
    1,
    0,
    milestone.created_at
FROM
    cl_budget_schema.project_schedule_milestone milestone
    JOIN cl_budget_schema.source_snapshot SNAPSHOT ON snapshot.id = milestone.source_snapshot_id
UNION ALL
SELECT
    'WIKIMEDIA_COMMONS',
    image.project_id,
    0,
    0,
    0,
    1,
    image.created_at
FROM
    cl_budget_schema.project_image image
)
SELECT
    fact.source_code,
    project.id AS project_id,
    project.wikidata_id,
    project.name AS project_name,
    project.is_active,
    SUM(fact.cost_claims)::INTEGER AS cost_claims,
    SUM(fact.metric_claims)::INTEGER AS metric_claims,
    SUM(fact.milestones)::INTEGER AS milestones,
    SUM(fact.image_claims)::INTEGER AS image_claims,
    MAX(fact.evidence_at) AS last_evidence_at
FROM
    source_facts fact
    JOIN cl_budget_schema.project project ON project.id = fact.project_id
GROUP BY
    fact.source_code,
    project.id,
    project.wikidata_id,
    project.name,
    project.is_active;

CREATE OR REPLACE VIEW cl_budget_schema.source_contribution_summary AS
SELECT
    source.code AS source_code,
    source.display_name,
    COUNT(contribution.project_id)::INTEGER AS matched_projects,
    COALESCE(SUM(contribution.cost_claims), 0)::INTEGER AS cost_claims,
    COALESCE(SUM(contribution.metric_claims), 0)::INTEGER AS metric_claims,
    COALESCE(SUM(contribution.milestones), 0)::INTEGER AS milestones,
    COALESCE(SUM(contribution.image_claims), 0)::INTEGER AS image_claims,
    MAX(contribution.last_evidence_at) AS last_evidence_at
FROM
    cl_budget_schema.source_registry SOURCE
    LEFT JOIN cl_budget_schema.source_project_contribution contribution ON contribution.source_code = source.code
GROUP BY
    source.code,
    source.display_name;

