CREATE OR REPLACE FUNCTION cl_budget_schema.save_budget_source_snapshot (p_source_code TEXT, p_external_id TEXT, p_title TEXT, p_canonical_url TEXT, p_reference_url TEXT, p_retrieved_at TIMESTAMP WITH TIME ZONE, p_payload JSONB)
    RETURNS BIGINT
    AS $$
DECLARE
    v_fingerprint CHAR(32);
    v_snapshot_id BIGINT;
    v_source cl_budget_schema.source_registry % ROWTYPE;
BEGIN
    IF p_payload IS NULL OR JSONB_TYPEOF(p_payload) <> 'object' THEN
        RAISE EXCEPTION 'Source snapshot payload must be a JSON object';
    END IF;
    SELECT
        registry.* INTO v_source
    FROM
        cl_budget_schema.source_registry registry
    WHERE
        registry.code = p_source_code
        AND registry.is_active
        AND registry.commercial_reuse_allowed;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Source % is not approved for commercial reuse', p_source_code;
    END IF;
    v_fingerprint := MD5(CONCAT_WS('|', p_title, p_canonical_url, p_reference_url, p_payload::TEXT, v_source.license_label, v_source.license_url, v_source.terms_url, v_source.attribution_text, v_source.commercial_reuse_allowed));
    INSERT INTO cl_budget_schema.source_snapshot (
        source_code,
        external_id,
        title,
        canonical_url,
        reference_url,
        retrieved_at,
        content_fingerprint,
        license_label,
        license_url,
        terms_url,
        attribution_text,
        commercial_reuse_allowed,
        payload)
    VALUES (
        p_source_code,
    LEFT (
        p_external_id,
        300),
    LEFT (
        p_title,
        500),
    p_canonical_url,
    NULLIF (
        BTRIM(
            p_reference_url), ''),
    p_retrieved_at,
    v_fingerprint,
    v_source.license_label,
    v_source.license_url,
    v_source.terms_url,
    v_source.attribution_text,
    v_source.commercial_reuse_allowed,
    p_payload)
ON CONFLICT (
    source_code,
    external_id,
    content_fingerprint)
    DO NOTHING;
    SELECT
        snapshot.id INTO v_snapshot_id
    FROM
        cl_budget_schema.source_snapshot SNAPSHOT
    WHERE
        snapshot.source_code = p_source_code
        AND snapshot.external_id =
    LEFT (p_external_id,
        300)
        AND snapshot.content_fingerprint = v_fingerprint;
    IF v_snapshot_id IS NULL THEN
        RAISE EXCEPTION 'Could not persist source snapshot %/%', p_source_code, p_external_id;
    END IF;
    RETURN v_snapshot_id;
END;
$$
LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION cl_budget_schema.publish_wikidata_candidate (p_wikidata_id TEXT, p_category TEXT, p_snapshot_at DATE)
    RETURNS BIGINT
    AS $$
DECLARE
    v_candidate RECORD;
    v_project_id BIGINT;
    v_question_id BIGINT;
    v_source_snapshot_id BIGINT;
    v_project_cost_id BIGINT;
    v_fact_id BIGINT;
    v_source_code VARCHAR(40);
    v_source_fingerprint CHAR(32);
    v_cost_fingerprint CHAR(32);
    v_source_hash CHAR(32);
    v_claim JSONB;
    v_fact_payload JSONB;
    v_cost_claims JSONB;
    v_metric_claims JSONB;
    v_milestone_claims JSONB;
BEGIN
    SELECT
        candidate.* INTO v_candidate
    FROM
        cl_budget_staging.wikidata_candidate source_candidate
    JOIN cl_budget_staging.wikidata_candidate_projection candidate
      ON candidate.wikidata_id = source_candidate.wikidata_id
     AND candidate.category = source_candidate.category
    WHERE
        source_candidate.wikidata_id = p_wikidata_id
        AND source_candidate.category = p_category
        AND source_candidate.last_fetched
        AND source_candidate.editorial_status <> 'REJECTED'
        AND (source_candidate.quality_status = 'AUTO_APPROVED'
            OR source_candidate.editorial_status = 'APPROVED')
        AND candidate.image_status = 'AVAILABLE'
        AND candidate.image_object_key IS NOT NULL
    FOR SHARE OF source_candidate;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Ready Wikidata candidate %/% does not exist', p_wikidata_id, p_category;
    END IF;
    v_source_fingerprint := MD5(CONCAT_WS('|', v_candidate.cost_source_name, v_candidate.cost_source_url, v_candidate.cost_reference_url, v_candidate.source_payload::TEXT));
