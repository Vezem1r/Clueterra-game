CREATE OR REPLACE VIEW cl_budget_schema.wikidata_rejection_summary AS
WITH observed_rejections AS (
    SELECT
        audit.category,
        audit.wikidata_id,
        'REJECTED'::TEXT AS status,
        audit.rejection_reason,
        audit.last_observed_at AS observed_at
    FROM
        cl_budget_staging.wikidata_rejection_audit audit
    UNION ALL
    SELECT
        snapshot.category,
        result.wikidata_id,
        result.status,
        result.rejection_reason,
        result.processed_at
    FROM
        cl_budget_staging.wikidata_enrichment_result RESULT
        JOIN cl_budget_staging.wikidata_discovery_snapshot SNAPSHOT ON snapshot.id = result.snapshot_id
),
latest_rejection AS (
    SELECT DISTINCT ON (category,
        wikidata_id)
        category,
        wikidata_id,
        status,
        rejection_reason,
        observed_at
    FROM
        observed_rejections
    ORDER BY
        category,
        wikidata_id,
        observed_at DESC
)
SELECT
    rejection.category,
    rejection.rejection_reason,
    COUNT(*) AS project_count,
    MAX(rejection.observed_at) AS last_observed_at
FROM
    latest_rejection rejection
WHERE
    rejection.status = 'REJECTED'
GROUP BY
    rejection.category,
    rejection.rejection_reason;

CREATE OR REPLACE VIEW cl_budget_schema.wikidata_discovery_progress AS
SELECT
    snapshot.id AS snapshot_id,
    snapshot.category,
    snapshot.processor_version,
    COUNT(DISTINCT seed.wikidata_id) AS discovered_seeds,
    COUNT(DISTINCT result.wikidata_id) FILTER (WHERE result.status = 'READY') AS ready_candidates,
    COUNT(DISTINCT result.wikidata_id) FILTER (WHERE result.status = 'REJECTED') AS rejected_candidates,
    COUNT(DISTINCT seed.wikidata_id) - COUNT(DISTINCT result.wikidata_id) AS pending_candidates,
    snapshot.started_at,
    snapshot.updated_at
FROM
    cl_budget_staging.wikidata_discovery_snapshot SNAPSHOT
    LEFT JOIN cl_budget_staging.wikidata_discovery_seed seed ON seed.snapshot_id = snapshot.id
    LEFT JOIN cl_budget_staging.wikidata_enrichment_result RESULT ON result.snapshot_id = snapshot.id
        AND result.wikidata_id = seed.wikidata_id
GROUP BY
    snapshot.id,
    snapshot.category,
    snapshot.processor_version,
    snapshot.started_at,
    snapshot.updated_at;

