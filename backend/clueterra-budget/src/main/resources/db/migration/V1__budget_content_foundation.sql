CREATE OR REPLACE FUNCTION cl_budget_schema.review_wikidata_candidates (p_candidates JSONB, p_review_status TEXT, p_review_note TEXT, p_reviewed_by TEXT)
    RETURNS INTEGER
    AS $$
DECLARE
    v_updated INTEGER;
BEGIN
    IF p_review_status NOT IN ('EDITORIAL_APPROVED', 'REJECTED') THEN
        RAISE EXCEPTION 'Unsupported editorial review status: %', p_review_status;
    END IF;
    IF p_candidates IS NULL OR JSONB_TYPEOF(p_candidates) <> 'array' OR JSONB_ARRAY_LENGTH(p_candidates) = 0 THEN
        RAISE EXCEPTION 'At least one candidate is required for bulk review';
    END IF;
    UPDATE
        cl_budget_staging.wikidata_candidate candidate
    SET
        editorial_status = CASE p_review_status
        WHEN 'EDITORIAL_APPROVED' THEN
            'APPROVED'
        ELSE
            p_review_status
        END,
        editorial_note = NULLIF (BTRIM(p_review_note), ''),
        editorial_by = NULLIF (BTRIM(p_reviewed_by), ''),
        editorial_at = NOW(),
        updated_at = NOW()
    WHERE
        candidate.last_fetched
        AND EXISTS (
            SELECT
                1
            FROM
                JSONB_ARRAY_ELEMENTS(p_candidates) requested
            WHERE
                requested ->> 'wikidataId' = candidate.wikidata_id
                AND requested ->> 'category' = candidate.category);
    GET DIAGNOSTICS v_updated = ROW_COUNT;
    IF p_review_status = 'REJECTED' THEN
        PERFORM
            cl_budget_schema.retire_budget_project (candidate.wikidata_id)
        FROM
            cl_budget_staging.wikidata_candidate candidate
        WHERE
            candidate.last_fetched
            AND candidate.editorial_status = 'REJECTED'
            AND EXISTS (
                SELECT
                    1
                FROM
                    JSONB_ARRAY_ELEMENTS(p_candidates) requested
                WHERE
                    requested ->> 'wikidataId' = candidate.wikidata_id
                    AND requested ->> 'category' = candidate.category);
    ELSIF p_review_status = 'EDITORIAL_APPROVED' THEN
        PERFORM
            cl_budget_schema.publish_wikidata_candidate (candidate.wikidata_id, candidate.category, CURRENT_DATE)
        FROM
            cl_budget_staging.wikidata_candidate candidate
        WHERE
            candidate.last_fetched
            AND candidate.editorial_status = 'APPROVED'
            AND candidate.image_status = 'AVAILABLE'
            AND candidate.image_resource_id IS NOT NULL
            AND EXISTS (
                SELECT
                    1
                FROM
                    JSONB_ARRAY_ELEMENTS(p_candidates) requested
                WHERE
                    requested ->> 'wikidataId' = candidate.wikidata_id
                    AND requested ->> 'category' = candidate.category);
    END IF;
    RETURN v_updated;
END;
$$
LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION cl_budget_schema.claim_budget_candidate_images (p_limit INTEGER, p_stale_before TIMESTAMP WITH TIME ZONE)
    RETURNS TABLE (
        wikidata_id VARCHAR,
        category VARCHAR,
        image_file_title VARCHAR,
        image_author_name_override TEXT,
        image_credit_override TEXT,
        attempt_count INTEGER
    )
    AS $$
BEGIN
    RETURN QUERY WITH selected AS (
        SELECT
            candidate.wikidata_id,
            candidate.category
        FROM
            cl_budget_staging.wikidata_candidate candidate
        WHERE
            candidate.last_fetched
            AND candidate.editorial_status <> 'REJECTED'
