-- Sync lifecycle and resumable external-source discovery.
CREATE TABLE IF NOT EXISTS cl_budget_schema.sync_run (
    id                   BIGINT                   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code          VARCHAR(50)              NOT NULL,
    status               VARCHAR(20)              NOT NULL,
    started_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    heartbeat_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    completed_at         TIMESTAMP WITH TIME ZONE,
    categories_attempted INTEGER                  NOT NULL DEFAULT 0,
    categories_succeeded INTEGER                  NOT NULL DEFAULT 0,
    records_discovered   INTEGER                  NOT NULL DEFAULT 0,
    records_retained     INTEGER                  NOT NULL DEFAULT 0,
    error_message        VARCHAR(2000),
    CONSTRAINT chk_budget_sync_run_status CHECK (status IN ('RUNNING', 'SUCCEEDED', 'PARTIAL', 'FAILED')),
    CONSTRAINT chk_budget_sync_run_counters CHECK (categories_attempted >= 0 AND categories_succeeded >= 0 AND categories_succeeded <= categories_attempted AND records_discovered >= 0 AND records_retained >= 0 AND records_retained <= records_discovered),
    CONSTRAINT chk_budget_sync_run_completion CHECK ((status = 'RUNNING' AND completed_at IS NULL) OR (status <> 'RUNNING' AND completed_at IS NOT NULL))
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_budget_sync_run_source_running ON cl_budget_schema.sync_run (source_code)
WHERE
    status = 'RUNNING';

CREATE INDEX IF NOT EXISTS idx_budget_sync_run_source_started ON cl_budget_schema.sync_run (source_code, started_at DESC);

