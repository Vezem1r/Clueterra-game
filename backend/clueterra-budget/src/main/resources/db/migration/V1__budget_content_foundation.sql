-- Editorial approval freezes the curated snapshot. Source refetch may continue to refresh
-- automatic candidates, but it must not deduplicate or republish manually approved content.

CREATE OR REPLACE FUNCTION cl_budget_schema.deduplicate_budget_candidates ()
    RETURNS INTEGER
    AS $$
DECLARE
    v_updated INTEGER;
BEGIN
    WITH ranked AS (
        SELECT
            wikidata_id,
            category,
            ROW_NUMBER() OVER (
                PARTITION BY wikidata_id
                ORDER BY CASE
                    WHEN editorial_status = 'APPROVED' THEN 0
                    WHEN candidate_origin = 'CURATED' THEN 1
                    ELSE 2
                END,
                quality_score DESC,
                interest_score DESC,
                source_rank,
                category
            ) AS candidate_rank
        FROM cl_budget_staging.wikidata_candidate
        WHERE last_fetched
    )
    UPDATE cl_budget_staging.wikidata_candidate candidate
    SET last_fetched = FALSE,
        updated_at = NOW()
    FROM ranked
    WHERE candidate.wikidata_id = ranked.wikidata_id
        AND candidate.category = ranked.category
        AND candidate.editorial_status <> 'APPROVED'
        AND ranked.candidate_rank > 1;

    GET DIAGNOSTICS v_updated = ROW_COUNT;
    RETURN v_updated;
END;
$$ LANGUAGE plpgsql;

