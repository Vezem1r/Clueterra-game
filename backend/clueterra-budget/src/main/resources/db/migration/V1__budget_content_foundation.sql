        updated_at = NOW()
    FROM
        selected
    WHERE
        candidate.wikidata_id = selected.wikidata_id
        AND candidate.category = selected.category
    RETURNING
        candidate.*
)
SELECT
    claimed.wikidata_id,
    claimed.category,
    claimed.image_file_title,
    CASE
        WHEN claimed.source_payload #>> '{imageAttributionOverride,fileTitle}' = claimed.image_file_title
            THEN NULLIF(BTRIM(claimed.source_payload #>> '{imageAttributionOverride,authorName}'), '')
        ELSE NULL
    END,
    CASE
        WHEN claimed.source_payload #>> '{imageAttributionOverride,fileTitle}' = claimed.image_file_title
            THEN NULLIF(BTRIM(claimed.source_payload #>> '{imageAttributionOverride,credit}'), '')
        ELSE NULL
    END,
    claimed.image_attempt_count
FROM
    claimed;
END;
$$
