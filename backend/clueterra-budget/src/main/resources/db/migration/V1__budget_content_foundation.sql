CREATE OR REPLACE FUNCTION cl_budget_schema.complete_wikidata_discovery (p_snapshot_id UUID, p_category TEXT)
    RETURNS INTEGER
    AS $$
DECLARE
    v_deleted INTEGER;
BEGIN
    PERFORM
        1
    FROM
        cl_budget_staging.wikidata_discovery_snapshot SNAPSHOT
