CREATE OR REPLACE VIEW cl_budget_staging.wikidata_candidate_projection AS
SELECT candidate.*,
       CASE WHEN image.external_id ~ '^[0-9]+$'
           THEN image.external_id::BIGINT
       END AS image_page_id,
       image.source_sha1 AS image_source_sha1,
       image.download_url AS image_thumbnail_url,
       image.original_url AS image_original_url,
       image.source_page_url AS image_source_page_url,
       image.author_name AS image_author_name,
       image.attribution_text AS image_credit,
       image.license_label AS image_license_label,
       image.license_url AS image_license_url,
       COALESCE(image.mime_type, image.source_mime_type) AS image_mime_type,
       image.byte_size AS image_source_bytes,
       COALESCE(image.width, image.source_width) AS image_width,
       COALESCE(image.height, image.source_height) AS image_height,
       image.object_key AS image_object_key
FROM cl_budget_staging.wikidata_candidate candidate
LEFT JOIN cl_media_schema.image_delivery image
       ON image.image_resource_id = candidate.image_resource_id;

CREATE OR REPLACE VIEW cl_budget_schema.candidate_review AS
SELECT
    candidate.*,
    CASE WHEN candidate.editorial_status = 'REJECTED' THEN
        'REJECTED'
    WHEN candidate.quality_status = 'NEEDS_REVIEW'
        AND candidate.editorial_status <> 'APPROVED' THEN
        'NEEDS_REVIEW'
    WHEN candidate.image_status = 'AVAILABLE' THEN
        'APPROVED'
    WHEN candidate.editorial_status = 'APPROVED' THEN
        'EDITORIAL_APPROVED'
    WHEN candidate.image_status = 'FAILED' THEN
        'NEEDS_IMAGE'
    ELSE
        'DISCOVERED'
    END AS review_status,
    candidate.editorial_note AS review_note,
    candidate.editorial_by AS reviewed_by,
    candidate.editorial_at AS reviewed_at
FROM
    cl_budget_staging.wikidata_candidate_projection candidate;

