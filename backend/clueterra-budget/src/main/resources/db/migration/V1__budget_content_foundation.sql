CREATE OR REPLACE FUNCTION cl_budget_schema.start_or_resume_wikidata_discovery (p_category TEXT, p_root_ids JSONB, p_processor_version INTEGER)
    RETURNS UUID
    AS $$
DECLARE
    v_snapshot_id UUID;
BEGIN
    IF p_root_ids IS NULL OR JSONB_TYPEOF(p_root_ids) <> 'array' OR JSONB_ARRAY_LENGTH(p_root_ids) = 0 THEN
        RAISE EXCEPTION 'At least one Wikidata root is required for %', p_category;
    END IF;
    IF p_processor_version <= 0 THEN
        RAISE EXCEPTION 'Wikidata processor version must be positive';
    END IF;
    IF EXISTS (
        SELECT
            1
        FROM
            JSONB_ARRAY_ELEMENTS_TEXT(p_root_ids) requested (root_id)
        WHERE
            requested.root_id !~ '^Q[1-9][0-9]*$')
        OR (
            SELECT
                COUNT(*)
            FROM
                JSONB_ARRAY_ELEMENTS_TEXT(p_root_ids)) <> (
        SELECT
            COUNT(DISTINCT root_id)
        FROM
            JSONB_ARRAY_ELEMENTS_TEXT(p_root_ids) requested (root_id)) THEN
    RAISE EXCEPTION 'Wikidata roots for % must be distinct Q identifiers', p_category;
END IF;
    SELECT
        snapshot.id INTO v_snapshot_id
    FROM
        cl_budget_staging.wikidata_discovery_snapshot SNAPSHOT
    WHERE
        snapshot.category = p_category
    FOR UPDATE;
    IF v_snapshot_id IS NOT NULL AND EXISTS (
        SELECT
            1
        FROM
            cl_budget_staging.wikidata_discovery_snapshot SNAPSHOT
        WHERE
            snapshot.id = v_snapshot_id AND (snapshot.root_ids <> p_root_ids OR snapshot.processor_version <> p_processor_version)) THEN
        DELETE FROM cl_budget_staging.wikidata_discovery_snapshot
        WHERE id = v_snapshot_id;
        v_snapshot_id := NULL;
    END IF;
    IF v_snapshot_id IS NULL THEN
        v_snapshot_id := GEN_RANDOM_UUID ();
        INSERT INTO cl_budget_staging.wikidata_discovery_snapshot (
            id,
            category,
            root_ids,
            processor_version)
        VALUES (
            v_snapshot_id,
            p_category,
            p_root_ids,
            p_processor_version);
    END IF;
INSERT INTO cl_budget_staging.wikidata_discovery_checkpoint (
    snapshot_id,
    root_id,
    cursor_value,
    status)
SELECT
    v_snapshot_id,
    requested.root_id,
    'http://www.wikidata.org/entity/Q0',
    'RUNNING'
FROM
    JSONB_ARRAY_ELEMENTS_TEXT(p_root_ids) requested (root_id)
ON CONFLICT (snapshot_id,
    root_id)
    DO NOTHING;
    UPDATE
        cl_budget_staging.wikidata_discovery_snapshot
    SET
        updated_at = NOW()
    WHERE
        id = v_snapshot_id;
    RETURN v_snapshot_id;
END;
$$
LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION cl_budget_schema.save_wikidata_discovery_page (p_snapshot_id UUID, p_category TEXT, p_root_id TEXT, p_cursor_value TEXT, p_complete BOOLEAN, p_seeds JSONB)
    RETURNS INTEGER
    AS $$
DECLARE
    v_buffered INTEGER;
    v_current_cursor TEXT;
    v_current_status TEXT;
BEGIN
    SELECT
        checkpoint.cursor_value,
        checkpoint.status INTO v_current_cursor,
        v_current_status
    FROM
        cl_budget_staging.wikidata_discovery_checkpoint CHECKPOINT
        JOIN cl_budget_staging.wikidata_discovery_snapshot SNAPSHOT ON snapshot.id = checkpoint.snapshot_id
    WHERE
        checkpoint.snapshot_id = p_snapshot_id
        AND checkpoint.root_id = p_root_id
        AND snapshot.category = p_category
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Wikidata discovery checkpoint %/%/% does not exist', p_snapshot_id, p_category, p_root_id;
    END IF;
    IF v_current_status = 'COMPLETE' THEN
        RAISE EXCEPTION 'Wikidata discovery checkpoint %/% is already complete', p_snapshot_id, p_root_id;
    END IF;
    -- The Wikidata query paginates with FILTER(STR(?item) > cursor) and ORDER BY ?item.
    -- Q identifiers therefore have to be compared lexicographically, not numerically.
    IF p_cursor_value COLLATE "C" < v_current_cursor COLLATE "C" THEN
        RAISE EXCEPTION 'Wikidata discovery cursor cannot move backwards (% -> %)', v_current_cursor, p_cursor_value;
    END IF;
    INSERT INTO cl_budget_staging.wikidata_discovery_seed (
        snapshot_id,
        root_id,
        wikidata_id,
        sitelink_count)
    SELECT
        p_snapshot_id,
        p_root_id,
        seed ->> 'wikidataId',
        (seed ->> 'sitelinkCount')::INTEGER
    FROM
        JSONB_ARRAY_ELEMENTS(COALESCE(p_seeds, '[]'::JSONB)) seed
ON CONFLICT (snapshot_id,
    root_id,
    wikidata_id)
    DO UPDATE SET
        sitelink_count = GREATEST (cl_budget_staging.wikidata_discovery_seed.sitelink_count, EXCLUDED.sitelink_count),
        discovered_at = NOW();
    SELECT
        COUNT(*)::INTEGER INTO v_buffered
    FROM
        cl_budget_staging.wikidata_discovery_seed seed
    WHERE
        seed.snapshot_id = p_snapshot_id
        AND seed.root_id = p_root_id;
    UPDATE
        cl_budget_staging.wikidata_discovery_checkpoint
    SET
        cursor_value = p_cursor_value,
        status = CASE WHEN p_complete THEN
            'COMPLETE'
        ELSE
            'RUNNING'
        END,
        records_buffered = v_buffered,
        completed_at = CASE WHEN p_complete THEN
            NOW()
            END,
        updated_at = NOW()
    WHERE
        snapshot_id = p_snapshot_id
        AND root_id = p_root_id;
    UPDATE
        cl_budget_staging.wikidata_discovery_snapshot
    SET
        updated_at = NOW()
    WHERE
        id = p_snapshot_id;
    RETURN v_buffered;
END;
$$
LANGUAGE plpgsql;

