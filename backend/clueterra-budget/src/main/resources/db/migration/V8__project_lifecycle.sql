CREATE TABLE cl_budget_schema.project_lifecycle_claim (
    id                 BIGINT                   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id         BIGINT                   NOT NULL REFERENCES cl_budget_schema.project (id) ON DELETE CASCADE,
    lifecycle_status   VARCHAR(30)              NOT NULL,
    as_of_date         DATE                     NOT NULL,
    source_snapshot_id BIGINT                   NOT NULL REFERENCES cl_budget_schema.source_snapshot (id),
    evidence_text      TEXT                     NOT NULL,
    claim_fingerprint  CHAR(32)                 NOT NULL,
    is_current         BOOLEAN                  NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_budget_project_lifecycle_claim UNIQUE (project_id, claim_fingerprint),
    CONSTRAINT chk_budget_project_lifecycle_status CHECK (
        lifecycle_status IN ('UNKNOWN', 'PLANNED', 'UNDER_CONSTRUCTION', 'ON_HOLD',
                             'CANCELLED', 'ABANDONED', 'COMPLETED')),
    CONSTRAINT chk_budget_project_lifecycle_evidence CHECK (BTRIM(evidence_text) <> ''),
    CONSTRAINT chk_budget_project_lifecycle_fingerprint CHECK (
        claim_fingerprint ~ '^[0-9a-f]{32}$')
);

CREATE UNIQUE INDEX uq_budget_project_lifecycle_current
    ON cl_budget_schema.project_lifecycle_claim (project_id)
    WHERE is_current;

CREATE INDEX idx_budget_project_lifecycle_status
    ON cl_budget_schema.project_lifecycle_claim (lifecycle_status, project_id)
    WHERE is_current;

CREATE OR REPLACE VIEW cl_budget_schema.project_current_lifecycle AS
SELECT
    project.id AS project_id,
    COALESCE(claim.lifecycle_status, 'UNKNOWN') AS lifecycle_status,
    claim.as_of_date,
    claim.source_snapshot_id,
    claim.evidence_text
FROM cl_budget_schema.project project
LEFT JOIN cl_budget_schema.project_lifecycle_claim claim
    ON claim.project_id = project.id
    AND claim.is_current;

CREATE OR REPLACE FUNCTION cl_budget_schema.materialize_candidate_lifecycle()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_candidate cl_budget_staging.wikidata_candidate%ROWTYPE;
    v_lifecycle JSONB;
    v_snapshot_id BIGINT;
    v_fingerprint CHAR(32);
    v_as_of_date DATE;
BEGIN
    SELECT candidate.*
    INTO v_candidate
    FROM cl_budget_staging.wikidata_candidate candidate
    WHERE candidate.wikidata_id = NEW.wikidata_id
      AND candidate.category = NEW.category
      AND candidate.last_fetched
    LIMIT 1;

    IF NOT FOUND THEN
        RETURN NEW;
    END IF;

    v_lifecycle := v_candidate.source_payload -> 'lifecycle';
    IF v_lifecycle IS NULL OR JSONB_TYPEOF(v_lifecycle) <> 'object' THEN
        RETURN NEW;
    END IF;
    IF COALESCE(v_lifecycle ->> 'status', '') NOT IN (
            'UNKNOWN', 'PLANNED', 'UNDER_CONSTRUCTION', 'ON_HOLD',
            'CANCELLED', 'ABANDONED', 'COMPLETED')
        OR BTRIM(COALESCE(v_lifecycle ->> 'evidenceText', '')) = '' THEN
        RETURN NEW;
    END IF;

    v_as_of_date := COALESCE(
        NULLIF(v_lifecycle ->> 'asOfDate', '')::DATE,
        v_candidate.fetched_at::DATE);
    v_fingerprint := MD5(CONCAT_WS('|',
        NEW.id,
        v_lifecycle ->> 'status',
        v_as_of_date,
        v_lifecycle ->> 'sourceKey',
        v_lifecycle ->> 'evidenceText'));

    v_snapshot_id := cl_budget_schema.save_budget_source_snapshot(
        COALESCE(v_lifecycle ->> 'sourceCode', 'WIKIDATA'),
        NEW.wikidata_id || ':' || COALESCE(v_lifecycle ->> 'sourceKey', 'LIFECYCLE'),
        COALESCE(v_lifecycle ->> 'sourceName', 'Project lifecycle status'),
        COALESCE(v_lifecycle ->> 'sourceUrl', v_candidate.source_url),
        v_lifecycle ->> 'referenceUrl',
        v_as_of_date::TIMESTAMP WITH TIME ZONE,
        JSONB_BUILD_OBJECT(
            'status', v_lifecycle ->> 'status',
            'asOfDate', v_as_of_date,
            'evidenceText', v_lifecycle ->> 'evidenceText'));

    UPDATE cl_budget_schema.project_lifecycle_claim
    SET is_current = FALSE
    WHERE project_id = NEW.id
      AND is_current
      AND claim_fingerprint <> v_fingerprint;

    INSERT INTO cl_budget_schema.project_lifecycle_claim (
        project_id,
        lifecycle_status,
        as_of_date,
        source_snapshot_id,
        evidence_text,
        claim_fingerprint,
        is_current)
    VALUES (
        NEW.id,
        v_lifecycle ->> 'status',
        v_as_of_date,
        v_snapshot_id,
        v_lifecycle ->> 'evidenceText',
        v_fingerprint,
        TRUE)
    ON CONFLICT (project_id, claim_fingerprint) DO UPDATE SET
        source_snapshot_id = EXCLUDED.source_snapshot_id,
        evidence_text = EXCLUDED.evidence_text,
        is_current = TRUE;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_budget_materialize_candidate_lifecycle
AFTER INSERT OR UPDATE OF source_hash ON cl_budget_schema.project
FOR EACH ROW
EXECUTE FUNCTION cl_budget_schema.materialize_candidate_lifecycle();

CREATE OR REPLACE FUNCTION cl_budget_schema.refresh_project_lifecycle_from_schedule(
    p_project_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    v_project cl_budget_schema.project%ROWTYPE;
    v_milestone RECORD;
    v_status VARCHAR(30);
    v_evidence_text TEXT;
    v_fingerprint CHAR(32);
BEGIN
    SELECT project.*
    INTO v_project
    FROM cl_budget_schema.project project
    WHERE project.id = p_project_id;

    IF NOT FOUND THEN
        RETURN;
    END IF;

    -- An explicit reviewed lifecycle claim is authoritative. Schedule-derived
    -- status exists only for candidates that do not provide one.
    IF EXISTS (
        SELECT 1
        FROM cl_budget_staging.wikidata_candidate candidate
        WHERE candidate.wikidata_id = v_project.wikidata_id
          AND candidate.category = v_project.category
          AND candidate.last_fetched
          AND JSONB_TYPEOF(candidate.source_payload -> 'lifecycle') = 'object'
          AND candidate.source_payload #>> '{lifecycle,status}' IN (
              'UNKNOWN', 'PLANNED', 'UNDER_CONSTRUCTION', 'ON_HOLD',
              'CANCELLED', 'ABANDONED', 'COMPLETED')
          AND BTRIM(COALESCE(
              candidate.source_payload #>> '{lifecycle,evidenceText}', '')) <> '') THEN
        RETURN;
    END IF;

    SELECT milestone.*, snapshot.payload AS source_payload
    INTO v_milestone
    FROM cl_budget_schema.project_schedule_milestone milestone
    JOIN cl_budget_schema.source_snapshot snapshot
      ON snapshot.id = milestone.source_snapshot_id
    WHERE milestone.project_id = p_project_id
      AND milestone.is_primary
      AND milestone.milestone_type IN ('ACTUAL_COMPLETION', 'OPENING')
      AND CASE milestone.date_precision
          WHEN 'DAY' THEN milestone.milestone_date
          ELSE MAKE_DATE(milestone.milestone_year, 12, 31)
          END <= v_project.cost_snapshot_at
    ORDER BY
        CASE milestone.milestone_type WHEN 'ACTUAL_COMPLETION' THEN 0 ELSE 1 END,
        CASE milestone.date_precision
            WHEN 'DAY' THEN milestone.milestone_date
            ELSE MAKE_DATE(milestone.milestone_year, 12, 31)
            END DESC
    LIMIT 1;

    IF FOUND THEN
        v_status := 'COMPLETED';
    ELSE
        SELECT milestone.*, snapshot.payload AS source_payload
        INTO v_milestone
        FROM cl_budget_schema.project_schedule_milestone milestone
        JOIN cl_budget_schema.source_snapshot snapshot
          ON snapshot.id = milestone.source_snapshot_id
        WHERE milestone.project_id = p_project_id
          AND milestone.is_primary
          AND milestone.milestone_type = 'CONSTRUCTION_START'
          AND CASE milestone.date_precision
              WHEN 'DAY' THEN milestone.milestone_date
              ELSE MAKE_DATE(milestone.milestone_year, 1, 1)
              END <= v_project.cost_snapshot_at
          AND EXISTS (
              SELECT 1
              FROM cl_budget_schema.project_schedule_milestone completion
              WHERE completion.project_id = p_project_id
                AND completion.is_primary
                AND completion.milestone_type IN (
                    'PLANNED_COMPLETION', 'CURRENT_COMPLETION_ESTIMATE')
                AND CASE completion.date_precision
                    WHEN 'DAY' THEN completion.milestone_date
                    ELSE MAKE_DATE(completion.milestone_year, 12, 31)
                    END > v_project.cost_snapshot_at)
        ORDER BY
            CASE milestone.date_precision
                WHEN 'DAY' THEN milestone.milestone_date
                ELSE MAKE_DATE(milestone.milestone_year, 1, 1)
                END DESC
        LIMIT 1;

        IF FOUND THEN
            v_status := 'UNDER_CONSTRUCTION';
        ELSE
            SELECT milestone.*, snapshot.payload AS source_payload
            INTO v_milestone
            FROM cl_budget_schema.project_schedule_milestone milestone
            JOIN cl_budget_schema.source_snapshot snapshot
              ON snapshot.id = milestone.source_snapshot_id
            WHERE milestone.project_id = p_project_id
              AND milestone.is_primary
              AND milestone.milestone_type IN (
                  'PLANNED_COMPLETION', 'CURRENT_COMPLETION_ESTIMATE')
              AND CASE milestone.date_precision
                  WHEN 'DAY' THEN milestone.milestone_date
                  ELSE MAKE_DATE(milestone.milestone_year, 12, 31)
                  END > v_project.cost_snapshot_at
            ORDER BY
                CASE milestone.milestone_type
                    WHEN 'CURRENT_COMPLETION_ESTIMATE' THEN 0 ELSE 1 END,
                CASE milestone.date_precision
                    WHEN 'DAY' THEN milestone.milestone_date
                    ELSE MAKE_DATE(milestone.milestone_year, 12, 31)
                    END
            LIMIT 1;

            IF FOUND THEN
                v_status := 'PLANNED';
            END IF;
        END IF;
    END IF;

    IF v_status IS NULL THEN
        UPDATE cl_budget_schema.project_lifecycle_claim
        SET is_current = FALSE
        WHERE project_id = p_project_id
          AND is_current;
        RETURN;
    END IF;

    v_evidence_text := COALESCE(
        NULLIF(BTRIM(v_milestone.source_payload ->> 'evidenceText'), ''),
        NULLIF(v_milestone.milestone_date::TEXT, ''),
        v_milestone.milestone_year::TEXT);
    v_fingerprint := MD5(CONCAT_WS('|',
        p_project_id,
        v_status,
        v_project.cost_snapshot_at,
        v_milestone.claim_fingerprint,
        'DERIVED_FROM_SCHEDULE'));

    UPDATE cl_budget_schema.project_lifecycle_claim
    SET is_current = FALSE
    WHERE project_id = p_project_id
      AND is_current
      AND claim_fingerprint <> v_fingerprint;

    INSERT INTO cl_budget_schema.project_lifecycle_claim (
        project_id,
        lifecycle_status,
        as_of_date,
        source_snapshot_id,
        evidence_text,
        claim_fingerprint,
        is_current)
    VALUES (
        p_project_id,
        v_status,
        v_project.cost_snapshot_at,
        v_milestone.source_snapshot_id,
        v_evidence_text,
        v_fingerprint,
        TRUE)
    ON CONFLICT (project_id, claim_fingerprint) DO UPDATE SET
        source_snapshot_id = EXCLUDED.source_snapshot_id,
        evidence_text = EXCLUDED.evidence_text,
        is_current = TRUE;
END;
$$;

CREATE OR REPLACE FUNCTION cl_budget_schema.refresh_project_lifecycle_from_schedule_trigger()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM cl_budget_schema.refresh_project_lifecycle_from_schedule(
        CASE WHEN TG_OP = 'DELETE' THEN OLD.project_id ELSE NEW.project_id END);
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_budget_refresh_lifecycle_from_schedule
AFTER INSERT OR UPDATE OR DELETE ON cl_budget_schema.project_schedule_milestone
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION cl_budget_schema.refresh_project_lifecycle_from_schedule_trigger();
