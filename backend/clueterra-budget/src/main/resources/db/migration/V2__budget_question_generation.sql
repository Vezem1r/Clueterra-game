CREATE TABLE IF NOT EXISTS cl_budget_schema.question_variant (
    id                     BIGINT                   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_question_id     BIGINT                   NOT NULL REFERENCES cl_budget_schema.question (id),
    comparison_question_id BIGINT                   REFERENCES cl_budget_schema.question (id),
    question_type          VARCHAR(30)              NOT NULL,
    generation_key         VARCHAR(120)             NOT NULL,
    answer_value           NUMERIC(24, 6),
    answer_unit            VARCHAR(40),
    answer_choice          VARCHAR(20),
    prompt_payload         JSONB                    NOT NULL,
    reveal_payload         JSONB                    NOT NULL,
    content_fingerprint    CHAR(32)                 NOT NULL,
    difficulty             VARCHAR(20)              NOT NULL,
    is_active              BOOLEAN                  NOT NULL DEFAULT TRUE,
    generated_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    retired_at             TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_budget_question_variant_revision UNIQUE (generation_key, content_fingerprint),
    CONSTRAINT chk_budget_question_variant_type CHECK (question_type IN (
        'HOW_MUCH',
        'CURRENT_ESTIMATE',
        'SPENT_SO_FAR',
        'ORIGINAL_BUDGET',
        'BUDGET_OVERRUN',
        'HOW_LATE',
        'HIGHER_LOWER',
        'COST_PER_UNIT'
    )),
    CONSTRAINT chk_budget_question_variant_key CHECK (BTRIM(generation_key) <> ''),
    CONSTRAINT chk_budget_question_variant_comparison CHECK (
        (
            question_type = 'HIGHER_LOWER'
            AND comparison_question_id IS NOT NULL
            AND comparison_question_id <> source_question_id
    )
        OR (
            question_type <> 'HIGHER_LOWER'
            AND comparison_question_id IS NULL
    )
    ),
    CONSTRAINT chk_budget_question_variant_answer CHECK (
        (
            question_type = 'HIGHER_LOWER'
            AND answer_value IS NULL
            AND answer_unit IS NULL
            AND answer_choice IN ('PRIMARY', 'COMPARISON')
    )
        OR (
            question_type <> 'HIGHER_LOWER'
            AND answer_value > 0
            AND BTRIM(answer_unit) <> ''
            AND answer_choice IS NULL
    )
    ),
    CONSTRAINT chk_budget_question_variant_prompt CHECK (JSONB_TYPEOF(prompt_payload) = 'object'),
    CONSTRAINT chk_budget_question_variant_reveal CHECK (JSONB_TYPEOF(reveal_payload) = 'object'),
    CONSTRAINT chk_budget_question_variant_fingerprint CHECK (content_fingerprint ~ '^[0-9a-f]{32}$'),
    CONSTRAINT chk_budget_question_variant_difficulty CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    CONSTRAINT chk_budget_question_variant_active CHECK (
        (is_active AND retired_at IS NULL)
        OR (NOT is_active AND retired_at IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_budget_question_variant_active_type
ON cl_budget_schema.question_variant (question_type, difficulty, id)
WHERE is_active;

CREATE UNIQUE INDEX IF NOT EXISTS uq_budget_question_variant_active_key
ON cl_budget_schema.question_variant (generation_key)
WHERE is_active;

CREATE INDEX IF NOT EXISTS idx_budget_question_variant_source
ON cl_budget_schema.question_variant (source_question_id, is_active);

CREATE TABLE IF NOT EXISTS cl_budget_schema.daily_challenge (
    id                 BIGINT                   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_date     DATE                     NOT NULL,
    generation_trigger VARCHAR(20)              NOT NULL,
    status             VARCHAR(20)              NOT NULL DEFAULT 'PUBLISHED',
    published_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_budget_daily_challenge_date UNIQUE (challenge_date),
    CONSTRAINT chk_budget_daily_challenge_trigger CHECK (generation_trigger IN ('MANUAL', 'SCHEDULED')),
    CONSTRAINT chk_budget_daily_challenge_status CHECK (status = 'PUBLISHED')
);

CREATE TABLE IF NOT EXISTS cl_budget_schema.daily_challenge_question (
    challenge_id        BIGINT   NOT NULL REFERENCES cl_budget_schema.daily_challenge (id) ON DELETE CASCADE,
    position            SMALLINT NOT NULL,
    question_variant_id BIGINT   NOT NULL REFERENCES cl_budget_schema.question_variant (id),
    PRIMARY KEY (challenge_id, position),
    CONSTRAINT uq_budget_daily_challenge_question UNIQUE (challenge_id, question_variant_id),
    CONSTRAINT chk_budget_daily_challenge_position CHECK (position BETWEEN 1 AND 5)
);

CREATE INDEX IF NOT EXISTS idx_budget_daily_challenge_question_variant
ON cl_budget_schema.daily_challenge_question (question_variant_id, challenge_id);

CREATE OR REPLACE FUNCTION cl_budget_schema.replace_budget_question_variants (
    p_variants JSONB
)
RETURNS TABLE (
    generated_count INTEGER,
    created_count INTEGER,
    retired_count INTEGER
)
AS $$
DECLARE
    v_generated_count INTEGER;
    v_created_count INTEGER;
    v_retired_count INTEGER;
    v_valid_count INTEGER;
BEGIN
    IF p_variants IS NULL OR JSONB_TYPEOF(p_variants) <> 'array' THEN
        RAISE EXCEPTION 'Budget question variants must be a JSON array';
    END IF;

    PERFORM PG_ADVISORY_XACT_LOCK(HASHTEXTEXTENDED('budget-question-variant-generation', 0));

    CREATE TEMP TABLE IF NOT EXISTS budget_question_variant_input (
        source_question_id BIGINT NOT NULL,
        comparison_question_id BIGINT,
        question_type TEXT NOT NULL,
        generation_key TEXT NOT NULL,
        answer_value NUMERIC,
        answer_unit TEXT,
        answer_choice TEXT,
        prompt_payload JSONB NOT NULL,
        reveal_payload JSONB NOT NULL,
        difficulty TEXT NOT NULL,
        content_fingerprint CHAR(32) NOT NULL
    ) ON COMMIT DROP;

    TRUNCATE pg_temp.budget_question_variant_input;

    INSERT INTO pg_temp.budget_question_variant_input (
        source_question_id,
        comparison_question_id,
        question_type,
        generation_key,
        answer_value,
        answer_unit,
        answer_choice,
        prompt_payload,
        reveal_payload,
        difficulty,
        content_fingerprint)
    SELECT
        candidate."sourceQuestionId",
        candidate."comparisonQuestionId",
        candidate."questionType",
        candidate."generationKey",
        candidate."answerValue",
        candidate."answerUnit",
        candidate."answerChoice",
        candidate."promptPayload",
        candidate."revealPayload",
        candidate.difficulty,
        MD5(CONCAT_WS(
            '|',
            candidate."sourceQuestionId"::TEXT,
            candidate."comparisonQuestionId"::TEXT,
            candidate."questionType",
            candidate."answerValue"::TEXT,
            candidate."answerUnit",
            candidate."answerChoice",
            candidate."promptPayload"::TEXT,
            candidate."revealPayload"::TEXT,
            candidate.difficulty))
    FROM JSONB_TO_RECORDSET(p_variants) AS candidate(
        "sourceQuestionId" BIGINT,
        "comparisonQuestionId" BIGINT,
        "questionType" TEXT,
        "generationKey" TEXT,
        "answerValue" NUMERIC,
        "answerUnit" TEXT,
        "answerChoice" TEXT,
        "promptPayload" JSONB,
        "revealPayload" JSONB,
        difficulty TEXT);

    SELECT COUNT(*)::INTEGER
    INTO v_generated_count
    FROM pg_temp.budget_question_variant_input;

    IF v_generated_count <> (
        SELECT COUNT(DISTINCT candidate.generation_key)
        FROM pg_temp.budget_question_variant_input candidate
    ) THEN
        RAISE EXCEPTION 'Budget question generation keys must be unique';
    END IF;

    SELECT COUNT(*)::INTEGER
    INTO v_valid_count
    FROM pg_temp.budget_question_variant_input candidate
    JOIN cl_budget_schema.question source_question
        ON source_question.id = candidate.source_question_id
        AND source_question.is_published
    LEFT JOIN cl_budget_schema.question comparison_question
        ON comparison_question.id = candidate.comparison_question_id
        AND comparison_question.is_published
    WHERE BTRIM(candidate.generation_key) <> ''
      AND candidate.question_type IN (
          'HOW_MUCH', 'CURRENT_ESTIMATE', 'SPENT_SO_FAR', 'ORIGINAL_BUDGET',
          'BUDGET_OVERRUN', 'HOW_LATE', 'HIGHER_LOWER', 'COST_PER_UNIT')
      AND JSONB_TYPEOF(candidate.prompt_payload) = 'object'
      AND JSONB_TYPEOF(candidate.reveal_payload) = 'object'
      AND candidate.difficulty IN ('EASY', 'MEDIUM', 'HARD')
      AND (
          (
              candidate.question_type = 'HIGHER_LOWER'
              AND candidate.comparison_question_id IS NOT NULL
              AND comparison_question.id IS NOT NULL
              AND comparison_question.project_id <> source_question.project_id
              AND candidate.answer_value IS NULL
              AND candidate.answer_unit IS NULL
              AND candidate.answer_choice IN ('PRIMARY', 'COMPARISON')
          )
          OR (
              candidate.question_type <> 'HIGHER_LOWER'
              AND candidate.comparison_question_id IS NULL
              AND candidate.answer_value > 0
              AND BTRIM(candidate.answer_unit) <> ''
              AND candidate.answer_choice IS NULL
          )
      );

    IF v_valid_count <> v_generated_count THEN
        RAISE EXCEPTION 'One or more generated BudgetGuessr questions are invalid or stale';
    END IF;

    SELECT COUNT(*)::INTEGER
    INTO v_created_count
    FROM pg_temp.budget_question_variant_input candidate
    LEFT JOIN cl_budget_schema.question_variant existing
        ON existing.generation_key = candidate.generation_key
        AND existing.content_fingerprint = candidate.content_fingerprint
    WHERE existing.id IS NULL;

    UPDATE cl_budget_schema.question_variant variant
    SET is_active = FALSE,
        retired_at = NOW()
    WHERE variant.is_active
      AND NOT EXISTS (
          SELECT 1
          FROM pg_temp.budget_question_variant_input candidate
          WHERE candidate.generation_key = variant.generation_key
            AND candidate.content_fingerprint = variant.content_fingerprint);
    GET DIAGNOSTICS v_retired_count = ROW_COUNT;

    INSERT INTO cl_budget_schema.question_variant (
        source_question_id,
        comparison_question_id,
        question_type,
        generation_key,
        answer_value,
        answer_unit,
        answer_choice,
        prompt_payload,
        reveal_payload,
        content_fingerprint,
        difficulty,
        is_active,
        generated_at,
        retired_at)
    SELECT
        candidate.source_question_id,
        candidate.comparison_question_id,
        candidate.question_type,
        candidate.generation_key,
        candidate.answer_value,
        candidate.answer_unit,
        candidate.answer_choice,
        candidate.prompt_payload,
        candidate.reveal_payload,
        candidate.content_fingerprint,
        candidate.difficulty,
        TRUE,
        NOW(),
        NULL
    FROM pg_temp.budget_question_variant_input candidate
    ON CONFLICT (generation_key, content_fingerprint) DO UPDATE
    SET is_active = TRUE,
        generated_at = NOW(),
        retired_at = NULL;

    RETURN QUERY SELECT v_generated_count, v_created_count, v_retired_count;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION cl_budget_schema.create_budget_daily_challenge (
    p_challenge_date DATE,
    p_generation_trigger TEXT,
    p_question_variant_ids JSONB
)
RETURNS TABLE (
    challenge_id BIGINT,
    challenge_date DATE,
    created BOOLEAN
)
AS $$
DECLARE
    v_challenge_id BIGINT;
    v_ids BIGINT[];
    v_reference_count INTEGER;
    v_distinct_project_count INTEGER;
BEGIN
    IF p_challenge_date IS NULL THEN
        RAISE EXCEPTION 'Budget challenge date is required';
    END IF;

    IF p_challenge_date < (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::DATE THEN
        RAISE EXCEPTION 'Budget challenge date cannot be in the past';
    END IF;

    IF p_generation_trigger NOT IN ('MANUAL', 'SCHEDULED') THEN
        RAISE EXCEPTION 'Unsupported Budget challenge generation trigger: %', p_generation_trigger;
    END IF;

    PERFORM PG_ADVISORY_XACT_LOCK(
        HASHTEXTEXTENDED('budget-daily-challenge:' || p_challenge_date::TEXT, 0)
    );

    SELECT challenge.id
    INTO v_challenge_id
    FROM cl_budget_schema.daily_challenge challenge
    WHERE challenge.challenge_date = p_challenge_date;

    IF v_challenge_id IS NOT NULL THEN
        RETURN QUERY SELECT v_challenge_id, p_challenge_date, FALSE;
        RETURN;
    END IF;

    IF p_question_variant_ids IS NULL OR JSONB_TYPEOF(p_question_variant_ids) <> 'array' THEN
        RAISE EXCEPTION 'Budget challenge question ids must be a JSON array';
    END IF;

    SELECT ARRAY_AGG(element.value::BIGINT ORDER BY element.ordinality)
    INTO v_ids
    FROM JSONB_ARRAY_ELEMENTS_TEXT(p_question_variant_ids)
        WITH ORDINALITY AS element(value, ordinality);

    IF CARDINALITY(v_ids) <> 5
        OR (SELECT COUNT(DISTINCT id) FROM UNNEST(v_ids) AS selected(id)) <> 5 THEN
        RAISE EXCEPTION 'A BudgetGuessr daily challenge requires exactly five distinct questions';
    END IF;

    IF (
        SELECT COUNT(*)
        FROM UNNEST(v_ids) AS selected(id)
        JOIN cl_budget_schema.question_variant variant
            ON variant.id = selected.id
            AND variant.is_active
        JOIN cl_budget_schema.question source_question
            ON source_question.id = variant.source_question_id
            AND source_question.is_published
        LEFT JOIN cl_budget_schema.question comparison_question
            ON comparison_question.id = variant.comparison_question_id
            AND comparison_question.is_published
        WHERE variant.comparison_question_id IS NULL
            OR comparison_question.id IS NOT NULL
    ) <> 5 THEN
        RAISE EXCEPTION 'A BudgetGuessr daily challenge contains inactive or stale questions';
    END IF;

    WITH selected_variants AS (
        SELECT variant.source_question_id, variant.comparison_question_id
        FROM UNNEST(v_ids) AS selected(id)
        JOIN cl_budget_schema.question_variant variant ON variant.id = selected.id
    ), referenced_projects AS (
        SELECT source_question.project_id
        FROM selected_variants selected
        JOIN cl_budget_schema.question source_question
            ON source_question.id = selected.source_question_id
        UNION ALL
        SELECT comparison_question.project_id
        FROM selected_variants selected
        JOIN cl_budget_schema.question comparison_question
            ON comparison_question.id = selected.comparison_question_id
    )
    SELECT COUNT(*)::INTEGER, COUNT(DISTINCT project_id)::INTEGER
    INTO v_reference_count, v_distinct_project_count
    FROM referenced_projects;

    IF v_reference_count <> v_distinct_project_count THEN
        RAISE EXCEPTION 'Projects cannot repeat within a BudgetGuessr daily challenge';
    END IF;

    INSERT INTO cl_budget_schema.daily_challenge (
        challenge_date,
        generation_trigger
    )
    VALUES (
        p_challenge_date,
        p_generation_trigger
    )
    RETURNING id INTO v_challenge_id;

    INSERT INTO cl_budget_schema.daily_challenge_question (
        challenge_id,
        position,
        question_variant_id
    )
    SELECT v_challenge_id, selected.ordinality::SMALLINT, selected.question_variant_id
    FROM UNNEST(v_ids) WITH ORDINALITY AS selected(question_variant_id, ordinality);

    RETURN QUERY SELECT v_challenge_id, p_challenge_date, TRUE;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION cl_budget_schema.assert_budget_challenge_size_from_challenge ()
RETURNS TRIGGER
AS $$
DECLARE
    v_challenge_id BIGINT := NEW.id;
BEGIN
    IF EXISTS (
        SELECT 1
        FROM cl_budget_schema.daily_challenge challenge
        WHERE challenge.id = v_challenge_id
    ) AND (
        SELECT COUNT(*)
        FROM cl_budget_schema.daily_challenge_question question
        WHERE question.challenge_id = v_challenge_id
    ) <> 5 THEN
        RAISE EXCEPTION 'Published BudgetGuessr challenge % must contain exactly five questions', v_challenge_id;
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION cl_budget_schema.assert_budget_challenge_size_from_question ()
RETURNS TRIGGER
AS $$
DECLARE
    v_challenge_id BIGINT;
BEGIN
    v_challenge_id := CASE
        WHEN TG_OP = 'DELETE' THEN OLD.challenge_id
        ELSE NEW.challenge_id
    END;

    IF EXISTS (
        SELECT 1
        FROM cl_budget_schema.daily_challenge challenge
        WHERE challenge.id = v_challenge_id
    ) AND (
        SELECT COUNT(*)
        FROM cl_budget_schema.daily_challenge_question question
        WHERE question.challenge_id = v_challenge_id
    ) <> 5 THEN
        RAISE EXCEPTION 'Published BudgetGuessr challenge % must contain exactly five questions', v_challenge_id;
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_budget_daily_challenge_size
AFTER INSERT OR UPDATE ON cl_budget_schema.daily_challenge
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION cl_budget_schema.assert_budget_challenge_size_from_challenge();

CREATE CONSTRAINT TRIGGER trg_budget_daily_challenge_question_size
AFTER INSERT OR UPDATE OR DELETE ON cl_budget_schema.daily_challenge_question
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION cl_budget_schema.assert_budget_challenge_size_from_question();
